# -*- coding: utf-8 -*-
"""三类高危问题识别（M8 第 7 步）。

为什么要有它：
    M7 收尾报告第七节点了三个"已知会翻车"的场景。它们不是随机错误，是**可识别**的：
    问题形态一出现，出错的概率就明显高于平均。所以界面提前提示"这类问题 M7 实测易错"，
    而不是假装什么都能答。

只提示、不阻断：
    风险条不改变请求、不改判定、不拦回答。判错的代价只是多一行提示；
    判对却能救一次"自信地答反"。
"""
from __future__ import annotations

import re

规则 = [
    {
        "类": "编号字段",
        "匹配": re.compile(r"\b[PURFGC]-\d+\b|§\s*\d+(?:\.\d+)*|`[A-Za-z_][A-Za-z0-9_]*`"),
        "标题": "编号／字段类问题，M7 实测易答错",
        "说明": "问题里点了编号、章节号或字段名。模型可能顺着这个编号编内容，而不是说“资料里没有”。",
        "依据": "M7 实例：问「§6.3 有配额规定吗」→ 编了一段（闸门只核 P- 家族，§ 编号拦不住）",
    },
    {
        "类": "同一件",
        "匹配": re.compile(r"同一|同一条|是不是同|是一样的吗|一样吗|等同|算不算同|相同吗|有区别吗"),
        "标题": "「是不是同一件」类问题，M7 实测答反",
        "说明": "需要跨节推理。模型倾向直接给“是／不是”，而两条文到底什么关系要读原文。",
        "依据": "M7 实例：问「P-12 和 §6.2① 是同一条吗」→ 答“是”（错）",
    },
    {
        "类": "怎么落地",
        "匹配": re.compile(r"怎么落地|如何落地|怎么实现|怎么做|落地路径|实施方案"),
        "标题": "「怎么落地／怎么做」类问题，M7 实测会用通识补写",
        "说明": "语料里往往只有规定、没有实施方案；模型会用行业通识补，看起来合理但不是本项目规则。",
        "依据": "M7 实例：问「自动化测试怎么落地」→ 答通用 ROI／选框架，不是本项目规则",
    },
]


def 识别(问题: str) -> list[dict]:
    """返回命中的风险条（同类只报一次，按规则表顺序）。"""
    文本 = str(问题 or "")
    出 = []
    for 条 in 规则:
        if 条["匹配"].search(文本):
            出.append({"类": 条["类"], "标题": 条["标题"],
                       "说明": 条["说明"], "依据": 条["依据"]})
    return 出
