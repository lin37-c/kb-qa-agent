def _提取引用编号(答案: str) -> list[int]:
    """从答案正文里提取实际引用到的材料编号（按出现顺序去重）。

    ★ 为什么需要它（2026-10-14 修）：
      原实现把「**召回到的全部材料**」都列为出处，但答案可能只用了其中一两条。
      实测：问题「改文件之前要先做什么」召回了 4 段，答案只引用了〔材料 3〕，
      而程序却把 4 段都列成"出处" —— 那 3 段**并不是这句话的来源**。
      这违反要求 R-3「每条可追证据」的本意：**出处应回答"这句话从哪来"，
      而不是"我检索到了什么"**。

    识别 〔材料 3〕／【材料 3】／[材料 3] 三种写法（模型实际会混用）。
    """
    import re as _re
    编号 = []
    for m in _re.finditer(r"[〔\[【]\s*材料\s*(\d+)\s*[〕\]】]", 答案):
        n = int(m.group(1))
        if n not in 编号:
            编号.append(n)
    return 编号


def _组装材料(命中: list[dict]) -> tuple[str, list[dict]]:
    """把检索结果排成带编号的材料块。返回（材料文本, 用到的元数据）。"""
    块 = []
    for i, h in enumerate(命中, 1):
        标题 = h.get("标题路径") or "(无标题)"
        块.append(
            f"【材料 {i}】\n"
            f"来源：{h['来源文件']} ＞ {标题}（原文第 {h['起始行']}–{h['结束行']} 行）\n"
            f"内容：\n{h['文本']}"
        )
    return "\n\n".join(块), 命中


def _调对话(prompt系统: str, prompt用户: str, max_tokens: int = 1200,
            流式回调=None) -> tuple[str, dict]:
    """调对话模型。返回（回答文本, 用量信息）。

    ★ 2026-10-26（M8 第 4 步）加 `流式回调`，**默认 None ⇒ 走原来的非流式路径，payload 一个字节不变**。
      为什么必须默认关：M7 的 8.3%／69.4% 是按这条路径测出来的；默认改了，那些数字就不再描述这份代码。
      传了回调才：payload 加 `"stream": true` 与 `stream_options.include_usage`（实测该接口
      在流末回 usage，见 T4），逐块把增量交给回调，最后拼成完整文本返回。
      ★ 回调由调用方保证不抛异常（它只往任务事件列表里追加）。
    """
    key = os.environ.get(配置.密钥环境变量名)
    if not key:
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as h:
                key, _ = winreg.QueryValueEx(h, 配置.密钥环境变量名)
        except Exception as e:  # noqa: BLE001
            raise RuntimeError(f"读不到 {配置.密钥环境变量名}：{e}") from e

    payload = {
        "model": 对话模型,
        "messages": [
            {"role": "system", "content": prompt系统},
            {"role": "user", "content": prompt用户},
        ],
        "temperature": 0,          # 严格模式：降低随机性（实测**不保证**跨调用一致，见文件头 ④ 的更正）
        "max_tokens": max_tokens,
    }
    头 = {"Authorization": f"Bearer {key}", "Content-Type": "application/json; charset=utf-8"}

    if 流式回调 is not None:
        payload["stream"] = True
        payload["stream_options"] = {"include_usage": True}
        t0 = time.time()
        片段: list[str] = []
        用量: dict = {}
        with requests.post(
            f"{服务地址}/chat/completions",
            headers=头,
            data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
            timeout=120,
            stream=True,
        ) as r:
            if r.status_code != 200:
                raise RuntimeError(f"对话接口 HTTP {r.status_code}: {r.text[:300]}")
            for 行 in r.iter_lines(decode_unicode=True):
                if not 行 or not 行.startswith("data:"):
                    continue
                体 = 行[5:].strip()
                if 体 == "[DONE]":
                    break
                try:
                    j = json.loads(体)
                except json.JSONDecodeError:
                    continue
                if j.get("usage"):
                    用量 = j["usage"]
                选项 = j.get("choices") or []
                if 选项:
                    增量 = (选项[0].get("delta") or {}).get("content")
                    if 增量:
                        片段.append(增量)
                        流式回调(增量)
        有量 = bool(用量)
        用量 = {
            "prompt_tokens": 用量.get("prompt_tokens", 0),
            "completion_tokens": 用量.get("completion_tokens", 0),
            "total_tokens": 用量.get("total_tokens", 0),
            "耗时秒": round(time.time() - t0, 2),
            "流式": True,
            "用量是否返回": 有量,
        }
        return "".join(片段).strip(), 用量

    t0 = time.time()
    r = requests.post(
        f"{服务地址}/chat/completions",
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json; charset=utf-8"},
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        timeout=120,
    )
    if r.status_code != 200:
        raise RuntimeError(f"对话接口 HTTP {r.status_code}: {r.text[:300]}")
    j = r.json()
    用量 = {
        "prompt_tokens": j.get("usage", {}).get("prompt_tokens", 0),
        "completion_tokens": j.get("usage", {}).get("completion_tokens", 0),
        "total_tokens": j.get("usage", {}).get("total_tokens", 0),
        "耗时秒": round(time.time() - t0, 2),
    }
    return j["choices"][0]["message"]["content"].strip(), 用量


# ---------- 主函数 ----------
def 回答(问题: str, 取前: int | None = None, 分组: str | None = None,
        检索完成回调=None, 流式回调=None) -> dict:
    """生成带出处的答案。

    返回 dict：
        问题 / 类型 / 分组 / 判定（检索层）/ 是否作答 / 答案 / 出处 / 用量 / 阈值说明

    ★ 2026-10-26（M8 第 4 步）两个钩子，**都默认 None ⇒ 行为与 M7 验证时完全一致**：
      · `检索完成回调(rr)`：检索一结束就回调，界面因此在**答案生成前**就能显示出处与档位；
      · `流式回调(增量文本)`：模型每吐一小段就回调一次，界面据此逐字显示。
      钩子只做"把内部状态透出去"，不改判定、不改提示词、不改取材条数。
    """
    类型 = 判类型(问题)
    条数 = 取前 or 取前条数(类型)

    # ---- 第一道闸门：检索 ----
    # ★ 2026-10-23（站 2 上线配置）：生产链路固定走「全库池 + 重排 100」，判定按重排尺度。
    #   依据：M7 阶段 B 定稿（全库 top-100 最优，128 无增益）＋ 站 2 阈值标定（C-33／F-105）。
    rr = R.检索(问题, 取前=条数, 分组=分组, 用重排=True, 重排池="全库", 重排候选数=100)

    if 检索完成回调 is not None:
        检索完成回调(rr)

    结果 = {
        "问题": 问题,
        "类型": 类型,
        "分组": rr["分组"],
        "查询扩展": rr["扩展词"],
        "召回条数": 条数,
        "检索判定": rr["判定"],
        "最高相似度": rr["最高相似度"],
        "阈值说明": rr["阈值说明"],
        "闸门分": rr["闸门分"],
        "闸门尺度": rr["闸门尺度"],
        "闸门阈值": rr["闸门阈值"],
        "是否作答": False,
        "答案": "",
        "出处": [],
        "用量": {},
        "命中": rr["结果"],
    }

    # 检索层若判为「不可作答」，直接拒答，不调 LLM
    # ★ 2026-10-23（F-106）：只读检索层给的结论，**不在这里重算阈值** —— 判定只有一个裁决点
    if not rr["可否作答"]:
        结果["答案"] = "资料里没有相关内容。"
        结果["拒答原因"] = (f"检索层判为不可作答：「{rr['判定']}」"
                            f"（闸门分 {rr['闸门分']}／{rr['闸门尺度']}尺度 < 阈值低 {rr['闸门阈值']['低']}）"
                            f"，未调用模型")
        return 结果

    材料文本, 命中 = _组装材料(rr["结果"])

    # ★★ 两阶段自检已**停用**（2026-10-25，v8）。
    #    实测：自检无论怎么措辞，都会砍掉 40~50% 的可答题（v6 作答率 50%、v7 60%），
    #    只换来 1~2 个点的幻觉下降 ⇒ 不划算，退回单次生成。
    #    取前条数上调（4/5/8 → 6/8/10）**保留**，它与自检无关，且实测把 CV-10 这类题的答案捞进了材料。

    用户提示 = 用户提示模板.format(问题=问题, 材料=材料文本)
    文本, 用量 = _调对话(系统提示, 用户提示, 流式回调=流式回调)

    结果["是否作答"] = True
    结果["答案"] = 文本
    结果["用量"] = 用量

    # ★ 出处只列「答案真正引用到的」材料（2026-10-14 修）
    引用编号 = _提取引用编号(文本)
    全部出处 = [
        {
            "编号": f"材料 {i}",
            "来源文件": h["来源文件"],
            "标题路径": h.get("标题路径", ""),
            "行号": f"{h['起始行']}–{h['结束行']}",
            "相似度": h["相似度"],
            "内容指纹": h.get("内容指纹", ""),
            "被引用": i in 引用编号,
        }
        for i, h in enumerate(命中, 1)
    ]
    结果["引用编号"] = 引用编号
    结果["出处"] = [o for o in 全部出处 if o["被引用"]]
    结果["未采用"] = [o for o in 全部出处 if not o["被引用"]]
    # 兜底：若一段编号都没提取到（模型没按格式标，或被截断），
    # 就退回"列全部"，并**明确标注**这是退路 —— 不能静默地少列出处，
    # 那会让"可追溯"变成假的（R-3）。
    if not 结果["出处"]:
        结果["出处"] = 全部出处
        结果["出处提取失败"] = True
    return 结果


def 格式化(结果: dict, 显示命中: int = 0) -> str:
    L = []
    L.append(f"提问：「{结果['问题']}」")
    L.append(f"  类型     : {结果['类型']}（召回 {结果['召回条数']} 段）")
    L.append(f"  分组     : {结果['分组']} ｜ 检索判定：{结果['检索判定']}（最高 {结果['最高相似度']}）")
    if 结果["查询扩展"]:
        L.append(f"  查询扩展 : 命中 {('、'.join(结果['查询扩展']))}")
    if not 结果["是否作答"]:
        L.append(f"  ⛔ 拒答   : {结果.get('拒答原因', '')}")
    L.append("")
    L.append("  ── 答案 ──")
    for line in 结果["答案"].split("\n"):
        L.append(f"  {line}")
    if 结果["出处"]:
        L.append("")
        标 = "（⚠️ 未能从答案里提取引用编号，退回列出全部召回）" if 结果.get("出处提取失败") else ""
        L.append(f"  ── 出处（答案实际引用到的，可回原文核对）{标}──")
        for o in 结果["出处"]:
            L.append(f"    {o['编号']}：{o['来源文件']} ＞ {o['标题路径']}（行 {o['行号']}）相似度 {o['相似度']}")
    if 结果.get("未采用"):
        L.append("")
        L.append(f"  ── 已召回但答案未采用（{len(结果['未采用'])} 段，仅供你判断检索质量）──")
        for o in 结果["未采用"]:
            L.append(f"    {o['编号']}：{o['来源文件']} ＞ {o['标题路径']}（相似度 {o['相似度']}）")
    if 结果["用量"]:
        u = 结果["用量"]
        L.append("")
        L.append(f"  用量：prompt {u['prompt_tokens']} ／ completion {u['completion_tokens']} ／ total {u['total_tokens']} tokens ｜ 耗时 {u['耗时秒']} 秒")
    if 显示命中:
        L.append("")
        L.append(f"  ── 召回明细（前 {显示命中} 段）──")
        for i, h in enumerate(结果["命中"][:显示命中], 1):
            t = h["文本"].replace("\n", " ⏎ ")
            L.append(f"    {i}. [{h['相似度']:.4f}] {h['来源文件']} ＞ {h['标题路径']}")
            L.append(f"       {t[:100]}…")
    return "\n".join(L)
