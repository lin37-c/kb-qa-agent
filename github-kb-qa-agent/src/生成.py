# ---------- 问题类型 ----------
# 对比型：需要多召回几段，让模型整合（F-6 的解法）
对比标记 = ("区别", "差异", "不同", "对比", "相比", "vs", "VS", "与…的差别", "有什么不一样")
# 说明型：需要更多材料支撑（如"为什么""原因"）
说明标记 = ("为什么", "原因", "是怎么", "如何保证", "原理")


def 判类型(问题: str) -> str:
    if any(m in 问题 for m in 对比标记):
        return "对比型"
    if any(m in 问题 for m in 说明标记):
        return "说明型"
    return "事实型"


def 取前条数(类型: str) -> int:
    """每类问题召回多少段：对比型要覆盖"两处分别怎么写"，所以最多。

    ★ 2026-10-25 回退为 4/5/8（v8 实测记录）：
      曾上调到 6/8/10，结果**作答率没变（85.9%）**，**幻觉率反而从 8.3% 升到 10.1%** ——
      材料越多，"看起来像但其实不对"的干扰也越多。多给材料是负收益，已回退。
    """
    return {"对比型": 8, "说明型": 5, "事实型": 4}[类型]


