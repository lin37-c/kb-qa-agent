"""生成层（M4）：把检索到的片段交给 LLM，产出**带出处**的答案。

在 RAG 里的位置：
    切片(M1) → 入库(M2) → 检索(M3) → 【生成】→ 用户看到的答案

本模块负责四件事（每件都对应一个具体要求或实测发现）：

① 带出处的答案
   要求 R-3「每条可追证据」＋ `AGENTS.md` 风险 4「生成答案必须带出处」。
   做法：把每段材料编号【材料 N】，并在 prompt 里**强制要求**答案里的每句话都标
   `〔材料 N〕`；答案末尾另附「出处」清单，可回原文核对。

② 「资料里没有就说没有」（不硬答）
   【禁令】P-07「禁止臆断」在生成层的落地。
   两道闸门：
     第一道（检索层）—— 检索层给的「可否作答」为 False → 直接返回"没有"，
                         **根本不调 LLM**（省一次调用，也避免它自由发挥）。
                         ★ 2026-10-23：本文件**不再自己比阈值**，只读 `检索结果["可否作答"]`；
                           裁决点只有一处（`检索.py` 的 `可否作答 = ... 闸门分 >= 阈低`）。
     第二道（生成层）—— prompt 里明确写"若材料不足以回答，就说资料里没有相关内容，
                         不得用常识补充"。**即使检索过了阈值，模型仍可拒答。**

③ 对比型提问（发现 F-6 的解法）
   M3 实测发现：问「候选区和正式区的区别是什么」召不回。
   原因不是措辞，是**语料分述无对比**——「候选阶段」写在 `维护规则 §6.2②`、
   「发布」写在 `§6.2⑤`，**没有任何一段专门讲区别**。
   → **检索层解决不了**（库里确实没有"对比"这个表述），
     但**生成层可以**：多召回几段，让 LLM 把两处描述**整合成对比**。
   做法：识别对比型提问 → 把召回数从 3 提到 8。

④ 严格模式与成本
   温度 0（**降低**随机性，但**不保证**跨调用一致）；max_tokens 可控；每次调用记录真实 token。
   ★ 2026-10-26 实测更正（原写「同一问题答案稳定、可复现」是**错的**）：
     同一问题、同一份材料（出处内容指纹完全相同）、temperature 0，连调两次的答案仍不同 ——
     两题实测 185→178 字、154→109 字，措辞与句子数都变。⇒ 任何「重跑应得同一段话」的假设都不成立，
     评测数字也只能描述**当次**运行（这一点要写进报告的失效条件）。
"""
