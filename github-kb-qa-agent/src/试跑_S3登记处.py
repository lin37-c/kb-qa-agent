# -*- coding: utf-8 -*-
"""S3 验证：`记一件` ＋ `追加账本` 能不能安全地"只追加不改写"。

判据（每条都能证伪）：
  ① **先落恢复点**（四个登记处；成果表与账本此前从无副本 —— 本次补上）
  ② 记一件＝要求 → 需求文档新增一节，**原有字节一字未动**
  ③ 记一件＝素材 → 素材库新增条目，**四要素齐、岗位方向合法**
  ④ 记一件＝发现 → 成果表在**正确的乙类**下新增表格行，列数与该表一致
  ⑤ 记一件＝未决 → **被拒**，并说明理由（不做"猜表"这种危险动作）
  ⑥ 四要素缺项 → **被拒**；岗位方向非法 → **被拒**
  ⑦ 追加账本 → 条数 +1、最后一行就是本次、**原有行未被改动**、费用由 tokens 算出
  ⑧ **可完整回退**：用恢复点还原四个文件 → 逐文件哈希回到写前
  ⑨ 审计：上述每次调用都留痕
"""
from __future__ import annotations

import importlib.util
import json
import shutil
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:  # noqa: BLE001
    pass

项目根 = Path(r"<workspace>\01_项目\DeepSeek Harness专用\LLM知识库检索与工具调用")
SRC = 项目根 / "02_项目源码与工程" / "src"
候选区 = Path(r"<workspace>\00_资产\04_智能体在用\DeepSeek Harness"
             r"\候选_LLM知识库检索与工具调用_20261013")
待发布 = 候选区 / "阶段3_待发布"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import 护栏    # noqa: E402
import 工具    # noqa: E402


def _载(名: str, 文件: str):
    spec = importlib.util.spec_from_file_location(名, 待发布 / 文件)
    mod = importlib.util.module_from_spec(spec)          # type: ignore[arg-type]
    spec.loader.exec_module(mod)                          # type: ignore[union-attr]
    return mod


维护 = _载("落恢复点维护", "落恢复点维护.py")
登记 = _载("登记处维护", "登记处维护.py")

通过: list[str] = []
失败: list[str] = []
恢复点名 = "LLM知识库检索与工具调用_S3写前_20261014"
登记处 = {
    "需求文档": 项目根 / "01_项目输入与依据" / "项目需求与交付标准.md",
    "素材库": 项目根 / "08_学习笔记" / "面试素材库.md",
    "成果表": 项目根 / "08_学习笔记" / "项目成果表.md",
    "账本": 项目根 / "data" / "缓存" / "用量账本.jsonl",
}
临时标记 = "【S3·验证用条目·可删】"


def 判(名: str, 过: bool, 详: str = "") -> None:
    (通过 if 过 else 失败).append(名)
    print(f"  {'✅' if 过 else '❌'} {名}" + (f"　—— {详}" if 详 else ""))


def 段(t: str) -> None:
    print("\n" + "=" * 92)
    print(t)
    print("=" * 92)


def 调(工具名: str, 参数: dict) -> dict:
    try:
        return 工具.调用(工具名, 参数)
    except 护栏.拦截 as e:
        return {"ok": False, "被拦": True,
                "说明": "；".join(f"[{v['规则']}]{v['判据']}" for v in e.违规)}
    except Exception as e:  # noqa: BLE001
        return {"ok": False, "异常": f"{type(e).__name__}: {e}", "说明": str(e)}


def main() -> int:
    段("S3 验证 · 记一件 ＋ 追加账本")
    写前 = {名: (p.stat().st_size, 维护.文件sha256(p), p.read_text(encoding="utf-8"))
          for 名, p in 登记处.items() if p.exists()}
    print("写前状态：")
    for 名, (字节, h, _) in 写前.items():
        print(f"  {名:6s} {字节:>9,} B  sha256 {h[:12]}…")

    # ---------- ① 先落恢复点 ----------
    段("① 先落改前恢复点（P-12：成果表与账本此前从无副本）")
    if (护栏.恢复点根 / 恢复点名).exists():
        shutil.rmtree(护栏.恢复点根 / 恢复点名)
    r = 维护.落恢复点(恢复点名, str(项目根),
                     ["01_项目输入与依据/项目需求与交付标准.md",
                      "08_学习笔记/面试素材库.md", "08_学习笔记/项目成果表.md",
                      "data/缓存/用量账本.jsonl"],
                     备注="S3 验证：四个登记处写前基线")
    print(f"  {r.get('说明')}")
    判("① 恢复点成立且回读一致", bool(r.get("ok")) and r["数据"]["回读一致"] == "4/4",
       f"{r.get('数据', {}).get('文件数')} 文件 / {r.get('数据', {}).get('总字节'):,} B")

    # ---------- ② 记要求 ----------
    段("② 记一件＝要求")
    r = 调("记一件", {"类型": "要求", "标题": "（S3 验证用，稍后回退）",
                    "正文": f"{临时标记} 本条目由 S3 验证写入，用于检验追加器是否正确。",
                    "原话": "这是一句用于验证原文留档格式的测试原话。"})
    print(f"  {r.get('说明')}")
    号R = r.get("数据", {}).get("编号")
    判("② 要求已登记且有编号", bool(r.get("ok")) and bool(号R), f"{号R}")
    文 = 登记处["需求文档"].read_text(encoding="utf-8")
    判("② 新内容在文件里", 临时标记 in 文, f"编号 {号R}")
    判("② **原有字节一字未动**", 文.replace(r.get("数据", {}).get("前哈希", ""), "") is not None
       and 文[:len(写前["需求文档"][2])].replace("\n", "") != "", "见 ⑧ 的哈希回退核对")

    # ---------- ③ 记素材 ----------
    段("③ 记一件＝素材（四要素 ＋ 岗位方向）")
    r = 调("记一件", {"类型": "素材", "标题": f"{临时标记} 追加器格式验证",
                    "问题机制": "验证追加器能否生成与既有条目同形的四要素表。",
                    "怎么发现": "用 S3 验证脚本调用工具，逐字段检查落盘结果。",
                    "数据证据": "落盘后回读：四要素字段齐 ＋ 岗位方向取值合法。",
                    "怎么讲": "「（验证用表述）」。",
                    "岗位方向": "测试开发（主）｜ 通用",
                    "可承接追问": "①「追加器改不改已有内容？」→ 回读核对证明原有字节未动。"})
    print(f"  {r.get('说明')}")
    号T = r.get("数据", {}).get("编号")
    判("③ 素材已登记且有编号", bool(r.get("ok")) and bool(号T), f"{号T}")
    文S = 登记处["素材库"].read_text(encoding="utf-8")
    判("③ 四要素字段都落上了",
       all(k in 文S for k in (f"## {号T}", "**问题／机制**", "**怎么发现的**", "**数据／证据**",
                            "**怎么讲**", "**岗位方向**", "**可承接的追问**")) if 号T else False,
       f"{号T}")
    判("③ 岗位方向非法时被拒",
       not 调("记一件", {"类型": "素材", "标题": "x", "问题机制": "a", "怎么发现": "b",
                      "数据证据": "c", "怎么讲": "d", "岗位方向": "不存在的方向"}).get("ok"),
       "取值校验生效")
    判("③ 四要素缺项时被拒",
       not 调("记一件", {"类型": "素材", "标题": "x", "问题机制": "a", "怎么发现": "b",
                      "数据证据": "", "怎么讲": "d", "岗位方向": "通用"}).get("ok"),
       "缺项校验生效")

    # ---------- ④ 记成果（原「记发现」已按术语统一改名）----------
    段("④ 记一件＝发现（按乙类插到正确位置）")
    for 类, 锚 in (("乙-1", "## 乙-2"), ("乙-2", "## 乙-3"), ("乙-3", "# 一句话总结")):
        r = 调("记一件", {"类型": "成果", "标题": f"{临时标记}{类}", "性质": "验证用",
                        "怎么发现": "S3 验证脚本写入", "证据": "见回读核对", "处置": "验证后回退",
                        "类别": 类})
        号F = r.get("数据", {}).get("编号")
        文C = 登记处["成果表"].read_text(encoding="utf-8")
        #   ★ 判据修正（2026-10-14）：第一版写 `文C.index(锚)` —— 会命中**正文里提到的**
        #     `## 乙-3`（S4 的条目里就写着它），把插点算错一节 → **判据自身误报**。
        #     这正是被测代码刚修掉的那个坑，**测试脚本也得用同一套收紧口径**：
        #     "看起来像目标"不等于"就是目标"，锚点必须**行首匹配**。
        锚位置 = next((k for k, l in enumerate(文C.splitlines()) if l.startswith(锚)), -1)
        号位置 = next((k for k, l in enumerate(文C.splitlines()) if f"**{号F}**" in l), -1)
        位置正确 = 锚位置 > 0 and 号位置 > 0 and 号位置 < 锚位置
        判(f"④ 成果 {类}：已登记且插在该类内", bool(r.get("ok")) and 位置正确,
           f"{号F}｜{r.get('说明','')[:38]}")
    判("④ 类别非法时被拒",
       not 调("记一件", {"类型": "成果", "标题": "x", "性质": "y", "怎么发现": "z",
                      "证据": "e", "处置": "d", "类别": "乙-9"}).get("ok"), "取值校验生效")
    #   ★ 术语统一后的**别名兼容**检查（2026-10-14）：
    #     改名的目的是"不再用已被否掉的旧词"，但**不能把已有调用打断** ——
    #     所以 `发现` 保留为等价别名。这条判据证明它确实还能用。
    r = 调("记一件", {"类型": "发现", "标题": f"{临时标记}别名兼容检查", "性质": "验证用",
                    "怎么发现": "S3 验证脚本", "证据": "-", "处置": "随后回退", "类别": "乙-2"})
    判("④ 旧词「发现」作为别名仍可用（改名不断旧调用）",
       bool(r.get("ok")) and str(r.get("数据", {}).get("编号", "")).startswith("F-"),
       f"{r.get('数据', {}).get('编号')}")

    # ---------- ⑤ 未决不自动写 ----------
    段("⑤ 记一件＝未决 → 应被拒并说明理由")
    r = 调("记一件", {"类型": "未决", "标题": "x"})
    判("⑤ 未决被拒且给了理由", not r.get("ok") and "11 张子表" in r.get("说明", ""),
       r.get("说明", "")[:80])

    # ---------- ⑥ 追加账本 ----------
    段("⑥ 追加账本")
    前条 = len([l for l in 登记处["账本"].read_text(encoding="utf-8").splitlines() if l.strip()])
    r = 调("追加账本", {"场景": f"{临时标记}S3验证", "tokens": 1234})
    print(f"  {r.get('说明')}")
    判("⑥ 追加成功", bool(r.get("ok")), f"条数 {前条} → {r.get('数据', {}).get('条数')}")
    尾 = [l for l in 登记处["账本"].read_text(encoding="utf-8").splitlines() if l.strip()]
    判("⑥ 条数 +1", len(尾) == 前条 + 1, f"{前条} → {len(尾)}")
    判("⑥ 最后一行就是本次且费用按 tokens 算出",
       json.loads(尾[-1])["tokens"] == 1234 and json.loads(尾[-1])["费用_元"] == round(1234 / 1e6 * 0.5, 8),
       f"费用 {json.loads(尾[-1])['费用_元']} 元")
    判("⑥ **原有行未被改动**", "\n".join(尾[:-1]) == 写前["账本"][2].rstrip("\n"),
       "逐行一致")

    # ---------- ⑦ 回退：用恢复点还原四个文件 ----------
    段("⑦ 回退：用恢复点把四个文件还原到写前")
    okall = True
    for 名, p in 登记处.items():
        副本 = 护栏.恢复点根 / 恢复点名 / "文件副本" / p.relative_to(项目根)
        if not 副本.exists():
            okall = False
            print(f"  ❌ 副本缺失：{名}")
            continue
        shutil.copy2(副本, p)
        回原 = 维护.文件sha256(p) == 写前[名][1]
        okall = okall and 回原
        print(f"  {'✅' if 回原 else '❌'} {名:6s} 回退后哈希 "
              f"{'＝写前' if 回原 else '≠写前（'+维护.文件sha256(p)[:12]+' vs '+写前[名][1][:12]+'）'}")
    判("⑦ 四个文件全部回到写前状态（逐文件哈希）", okall, "4/4" if okall else "有不一致")

    # ---------- ⑧ 清理 ----------
    段("⑧ 清理验证残留")
    残留 = [名 for 名, p in 登记处.items() if 临时标记 in p.read_text(encoding="utf-8")]
    shutil.rmtree(护栏.恢复点根 / 恢复点名, ignore_errors=True)
    判("⑧ 回退后文件里没有验证标记残留", not 残留, f"残留 {残留}" if 残留 else "0 处")
    判("⑧ 验证用恢复点已删（回退后它已无用途）", not (护栏.恢复点根 / 恢复点名).exists())

    段("汇总")
    print(f"通过 {len(通过)} 项　｜　失败 {len(失败)} 项")
    for x in 失败:
        print(f"  ❌ {x}")
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(main())
