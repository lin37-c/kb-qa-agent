    编造域名 = [w for w in ("localhost", "adobe", "0.0.0.0", "broadcasthost", "ip6-")
              if w in 答3.lower()]
    声称读到 = [w for w in ("文件内容", "里面写着", "内容如下", "读到了", "内容为")
              if w in 答3]
