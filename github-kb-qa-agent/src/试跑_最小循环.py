    判("② 被拒后未重复同一动作（没有硬绕）",
       len([x for x in r2["已调"] if x["工具"] in ("写候选", "试写_无需恢复点")]) <= 2,
       f"写类调用 {len([x for x in r2['已调'] if x['工具'] in ('写候选', '试写_无需恢复点')])} 次")

