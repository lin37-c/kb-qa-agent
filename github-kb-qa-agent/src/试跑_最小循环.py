def 调对话(messages: list[dict], 轮: int) -> tuple[dict, dict]:
    payload = {"model": 配置.对话模型, "messages": messages, "tools": 工具.表单(),
              "tool_choice": "auto", "temperature": 0}
    t0 = time.time()
    r = requests.post(f"{配置.服务地址}/chat/completions",
                      headers={"Authorization": f"Bearer {取密钥()}",
                               "Content-Type": "application/json; charset=utf-8"},
                      data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
                      timeout=180)
    if r.status_code != 200:
        raise RuntimeError(f"HTTP {r.status_code}: {r.text[:400]}")
    j = r.json()
    u = dict(j.get("usage", {}))
    u["耗时秒"] = round(time.time() - t0, 2)
    u["轮次"] = 轮
    return j["choices"][0]["message"], u


def 疑似伪调用(文: str) -> list[str]:
    """U-39：检测「把工具调用当文本写出来」的伪调用。

    背景（F-47 实测）：模型的 `tool_calls` 为空，但 `content` 里就一行
    `列目录("…")` —— **看起来像在调工具，其实什么都没执行**。

    判据：`content` 里出现 **工具集里真实存在的工具名** 紧跟 `(`（允许中间有空格）。
    ★ 为什么用「工具名单」而不是随便匹配 `\\w+(`：后者会把正文里的普通括号（如「（见下）」）
      误判成伪调用。**只认真实工具名** → 误报率降到可接受。

    返回：命中的工具名列表（空＝没有伪调用）。
    """
    import re as _re
    名s = sorted(工具.TOOLS.keys(), key=len, reverse=True)   # 长名优先，避免"查知识库"被"查"抢
    命中 = []
    for 名 in 名s:
        if _re.search(_re.escape(名) + r"\s*\(", 文):
            命中.append(名)
    return 命中


def 回灌文本(结果: dict, 上限: int = 1200) -> str:
    """U-40：回灌给模型时，**被截断必须说出来**。

    背景（F-48 实测）：`读文件` 能返回 2.6 万字符，而回灌只给模型 1200 字符
    （为控上下文）—— **但原文里没有截断信号**，模型可能**以为看到了全文**就下结论
    （实测它答"文件内容较多，无法统计"：诚实没问题，**根因是我们的上下文取舍未标注**）。

    ★ 判据：**凡给模型看的内容被截断，必须在返回值里说出来**（含"还剩多少"）。
    ★ 注意：`读文件` 自己已有 `是否截断` 字段，但它说的是**行区间内的截断**；
      这里说的是**回灌层的截断** —— 两层都要标注，**不能因为工具说了就以为回灌也说了**。
    """
    文 = json.dumps(结果, ensure_ascii=False)
    if len(文) <= 上限:
        return 文
    剩 = len(文) - 上限
    return (文[:上限]
            + f"\n\n⚠️ 【回灌已截断】本次工具返回共 {len(文):,} 字符，"
              f"上面只给出了前 {上限:,} 字符，**还有约 {剩:,} 字符没有给到你**。"
              f"★ 因此**不要**基于以上内容断言『全文如此』或『内容较多无法统计』——"
              f"如需更多，请改用 `读文件` 的 `起行/止行/最大字符` 参数**分段读取**。")


def 跑(题号: str, 问题: str, 历史: list[dict] | None = None,
      最多轮: int = 6) -> dict:
    """跑一次最小循环。返回 {最终答案, 轮数, 工具调用, 工具返回, 用量, messages}。"""
    print(f"\n【{题号}】{问题}")
    messages = [{"role": "system", "content": 系统提示}]
    if 历史:
        messages.extend(历史)
    messages.append({"role": "user", "content": 问题})
    已调, 用量s, 工具返回文 = [], [], []
    最终, 轮数 = "", 0
    前审计 = 审计行数()

    # ★ U-39：伪调用**最多重试 1 次**。为什么限 1 次：
    #   若模型连续两次都写成文本，说明"提示它改调用方式"这条路对它无效 ——
    #   再重试只会白烧 token；此时应**如实把这次判为失败**，而不是假装成功。
    伪重试 = 0
    达到上限且伪调用 = False
    for 轮 in range(1, 最多轮 + 1):
        轮数 = 轮
        msg, u = 调对话(messages, 轮)
        用量s.append(u)
        费用表.append(u)
        calls = msg.get("tool_calls") or []
        if not calls:
            最终 = (msg.get("content") or "").strip()
            # ★ U-39：**先判是不是伪调用**，再决定是否当最终答案。
            #   判据：`tool_calls` 为空，但 `content` 里写了「真实工具名(」形态 → 它其实想调工具，
            #   只是写成了文本（F-47 实测发生 1 次）。此时**不能当最终答案** ——
            #   那样会得到"看起来执行了、其实什么都没执行"的结果。
            伪 = 疑似伪调用(最终)
            if 伪 and 伪重试 < 1:
                伪重试 += 1
                print(f"  第 {轮} 轮：**伪调用**（content 里写了 {伪}，tool_calls 为空）"
                      f"→ 提示模型改用真正的工具调用，重试一次")
                messages.append({"role": "assistant", "content": 最终})
                messages.append({"role": "user", "content":
                                 "你上一条**把工具调用写成了普通文本**（" + "、".join(伪) + "），"
                                 "那样**不会真正执行**。请**改用真正的工具调用（tool_calls）**重新发起；"
                                 "如果你已经不需要工具、可以凭已有信息回答，就直接给出最终答案。"})
                continue
            if 伪:
                print(f"  第 {轮} 轮：**再次出现伪调用**（{伪}）→ 已达到重试上限，按最终答案处理"
                      f"（★ 这种答案不可信，判据会据此判失败）")
            print(f"  第 {轮} 轮：**无工具调用** → 给出最终答案（{len(最终)} 字）")
            messages.append({"role": "assistant", "content": 最终})
            break
        print(f"  第 {轮} 轮：请求 {len(calls)} 个工具调用")
        messages.append({"role": "assistant", "content": msg.get("content") or "",
                         "tool_calls": calls})
        for c in calls:
            名 = c["function"]["name"]
            try:
                参 = json.loads(c["function"].get("arguments") or "{}")
            except json.JSONDecodeError:
                参 = {"__解析失败__": c["function"].get("arguments")}
            print(f"     → {名}({json.dumps(参, ensure_ascii=False)[:150]})")
            已调.append({"工具": 名, "参数": 参})
            try:
                结果 = 工具.调用(名, 参)
                判定 = "放行" if 结果.get("ok") else "返回失败"
            except 护栏.拦截 as e:
                结果 = {"ok": False, "说明": "★ 被护栏拦截",
                        "违规": [{"规则": v["规则"], "判据": v["判据"]} for v in e.违规]}
                判定 = "★护栏拦截"
            except Exception as e:  # noqa: BLE001
                结果 = {"ok": False, "说明": f"异常：{type(e).__name__}: {e}"}
                判定 = "异常"
            已调[-1]["判定"] = 判定
            print(f"       判定：{判定}　{str(结果.get('说明',''))[:110]}")
            文 = json.dumps(结果, ensure_ascii=False)
            工具返回文.append(文)
            messages.append({"role": "tool", "tool_call_id": c.get("id", ""),
                             # ★ U-40：回灌被截断时**显式说出来**（含"还剩多少"），
                             #   不然模型可能以为看到了全文就下结论（F-48 实测）。
                             "content": 回灌文本(结果, 上限=1200)})
        if 轮 == 最多轮:
            print(f"  达到上限 {最多轮} 轮，未收敛")
            最终 = (msg.get("content") or "").strip()
            # ★ U-39 的判据延伸：**"达到轮数上限"时的答案同样是未完成的**
            #   若它此时又写成伪调用 → 必须让判据知道（否则会被当成合格答案）。
            if 疑似伪调用(最终):
                达到上限且伪调用 = True

    print(f"  ── 最终答案：\n     {最终[:600]}")
    return {"最终": 最终, "轮数": 轮数, "已调": 已调, "工具返回": 工具返回文,
            "用量": 用量s, "messages": messages, "审计增量": 审计行数() - 前审计,
            # ★ U-39：把两个"这次答案不可信"的信号带出去，供判据使用
            "伪调用重试": 伪重试, "伪调用": 疑似伪调用(最终),
            "达上限且伪调用": 达到上限且伪调用}


def 数字有出处(答案: str, 工具返回: list[str]) -> tuple[bool, list[str]]:
    """判据：答案里出现的"像数字的片段"，是否能在工具返回里找到（含格式化差异）。"""
    import re
    # 只挑"有意义"的数字：≥3 位、或带小数的金额/比率
    候选 = set(re.findall(r"\d[\d,]{2,}(?:\.\d+)?", 答案))
    池 = " ".join(工具返回)
    池2 = 池.replace(",", "")
    无出处的 = []
    for x in 候选:
        if x in 池 or x.replace(",", "") in 池2 or x in 池2:
            continue
        无出处的.append(x)
    return (not 无出处的), 无出处的


