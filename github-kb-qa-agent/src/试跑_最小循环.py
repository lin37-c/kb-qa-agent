    答1 = r1["最终"]
    #   ★ 判据修正（2026-10-14，第三次 —— 这条改了三版，每次都因为"路径不通"）：
    #     事实链：① 最初文件名靠猜 → 找不到；② 补了 `列目录` → 找到了文件；
    #     ③ 但 `读文件` 返回 2.6 万字符，而**回灌给模型只截 1200 字符**（控上下文），
    #        模型看不到全部 → 它**如实回答"文件较大，无法从文本中统计"**。
