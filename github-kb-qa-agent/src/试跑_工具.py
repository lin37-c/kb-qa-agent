def 审计行数() -> int:
    if not 护栏.审计日志.exists():
        return 0
    return len([l for l in 护栏.审计日志.read_text(encoding="utf-8").splitlines() if l.strip()])


def 账本费用() -> float:
    """从账本算累计费用。★ 字段名是 `费用_元`（与 向量化._记用量 一致）——
    第一版写成 `费用`，得到"账本可读但累计 0 元"，**读数错比读不到更危险**。"""
    账 = 项目根 / "data" / "缓存" / "用量账本.jsonl"
    if not 账.exists():
        return 0.0
    总 = 0.0
    for l in 账.read_text(encoding="utf-8").splitlines():
        if not l.strip():
            continue
        try:
            总 += float(json.loads(l).get("费用_元", 0) or 0)
        except Exception:  # noqa: BLE001
            pass
    return 总


def 调(工具名: str, 参数: dict, 说明: str, 期望ok: bool = True) -> dict:
    """调一次工具，并把"是否过护栏"用审计行数增量证明出来。"""
    前审计, 前费 = 审计行数(), 账本费用()
    t0 = time.time()
    try:
        r = 工具.调用(工具名, 参数)
        异常 = ""
    except 护栏.拦截 as e:
        r = {"ok": False, "工具": 工具名, "说明": "被护栏拦截", "数据": {}, "证据": [],
             "违规": e.违规}
        异常 = "护栏拦截"
    except Exception as e:  # noqa: BLE001
        r = {"ok": False, "工具": 工具名, "说明": f"异常：{type(e).__name__}: {e}",
             "数据": {}, "证据": []}
        异常 = "异常"
    耗 = time.time() - t0
    后审计, 后费 = 审计行数(), 账本费用()

    print(f"\n【{说明}】")
    print(f"  调用  ：{工具名}({json.dumps(参数, ensure_ascii=False)[:110]})")
    print(f"  结果  ：ok={r.get('ok')}　{r.get('说明', '')[:150]}")
    print(f"  证据  ：{len(r.get('证据') or [])} 条")
    print(f"  耗时  ：{耗:.2f} 秒　｜　审计行数 {前审计} → {后审计}"
          f"　｜　账本费用 {前费:.6f} → {后费:.6f}（＋{后费 - 前费:.6f}）")

    # 判据组
    判(f"{说明}｜未抛异常", 异常 in ("", "护栏拦截"), 异常)
    判(f"{说明}｜返回结构与期望一致", bool(r.get("ok")) == 期望ok, f"ok={r.get('ok')}")
    判(f"{说明}｜工具确实过了护栏（审计 +1）", 后审计 - 前审计 == 1, f"增量 {后审计 - 前审计}")
    if 期望ok:
        判(f"{说明}｜证据非空", bool(r.get("证据")), f"{len(r.get('证据') or [])} 条")
    return r


