# -*- coding: utf-8 -*-
"""第 0.5 步演示：把一段中文变成 1024 个数字。

这份脚本是"教学演示"，不是正式流程。它的目的是让你亲眼看到：
    文字 → 向量 这一步到底发生了什么，输出长什么样，每个数字是什么意思。

运行：
    cd 02_项目源码与工程
    .venv\\Scripts\\python.exe -B -X utf8 src\\演示_文字变向量.py
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np

import 配置
import 向量化
from 缓存 import 余弦相似度矩阵, 归一化


def 标题(t: str) -> None:
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)


def 主流程() -> int:
    标题("第 0.5 步：文字 → 向量（亲眼看到 embedding 长什么样）")

    # ---------- 1. 单条 ----------
    文本 = "改动任何文件前必须先落实改前恢复点。"
    print(f"\n【1】输入文字（{len(文本)} 个字）：")
    print(f"    「{文本}」")
    print("\n    正在调用 embedding-3 ……")
    t0 = time.time()
    v = 向量化.向量化单条(文本, 场景="演示_单条")
    耗时 = time.time() - t0

    arr = np.array(v, dtype=np.float32)
    print(f"\n【2】返回结果：")
    print(f"    类型          : {type(v).__name__}，里面装 {len(v)} 个 float")
    print(f"    向量维度      : {len(v)}   （配置里设的 {配置.向量维度} 维）")
    print(f"    总耗时        : {耗时:.2f} 秒（含一次网络往返）")
    print(f"\n    前 8 个数字   : {[round(float(x), 4) for x in v[:8]]}")
    print(f"    中间 8 个数字 : {[round(float(x), 4) for x in v[500:508]]}")
    print(f"    最后 8 个数字 : {[round(float(x), 4) for x in v[-8:]]}")

    # ---------- 2. 统计特征（★这里是实测事实，不是理论） ----------
    print(f"\n【3】这 1024 个数字的统计特征（实测）：")
    print(f"    最小值        : {arr.min():.4f}")
    print(f"    最大值        : {arr.max():.4f}")
    print(f"    平均值        : {arr.mean():.6f}   ← 接近 0（各方向正负抵消）")
    print(f"    标准差        : {arr.std():.6f}")
    模长 = float(np.linalg.norm(arr))
    print(f"    模长(平方和开方): {模长:.4f}")
    print(f"""
    ★ 一个必须纠正的常见误解：
        很多教程说"embedding 输出是归一化的、模长=1"。**智谱 embedding-3 不是。**
        实测模长 = {模长:.4f}，明显小于 1。

        不归一化会有什么后果？
          直接算"点积"（对应位置相乘再求和）时，自己和自己点积 = {模长:.4f}² = {模长**2:.4f}，
          而不是 1。所以不做归一化，相似度数值就没法按 0~1 解释。
        正确做法：
          先各自除以自己的模长（归一化），再点积——这才叫**余弦相似度**。
          本项目的 缓存.py 里 余弦相似度矩阵() 就是干这个的。
""")

    # ---------- 3. 缓存与确定性 ----------
    print("【4】同一段文字再算一次，结果会变吗？还会再花钱吗？")
    t0 = time.time()
    v2 = 向量化.向量化单条(文本, 场景="演示_重复验证")
    耗时2 = time.time() - t0
    最大差 = float(np.max(np.abs(np.array(v2, dtype=np.float32) - arr)))
    print(f"    两次结果的逐元素最大差 : {最大差:.2e}   （{最大差:.0e} = 0.0000…）")
    print(f"    第一次耗时 {耗时:.2f} 秒 → 第二次耗时 {耗时2:.4f} 秒")
    print(f"    两次是否完全相同       : {'是 ✅' if 最大差 == 0 else '否'}")

    缓存 = 向量化.缓存实例()
    print(f"\n    缓存条数 : {缓存.已缓存条数}")
    print(f"    本次命中 : {缓存.本次命中} 次 ← 第二次直接读本地，没有调接口")
    print(f"    本次未命中: {缓存.本次未命中} 次")
    print(f"""
    ★ 这里有个重要认知，比"接口稳不稳定"更关键：
        我们**不依赖**接口每次返回一模一样。
        只要内容的指纹没变，就直接复用本地存的那份向量——接口根本不参与。
        所以接口哪怕有浮点抖动，也不影响我们，因为我们不重新调它。

        缓存不是为了"省一点点钱"，而是为了：
          切片参数调 10 次，只要语料没变，第 2 次到第 10 次费用都是 0。
""")

    # ---------- 4. 批处理 ----------
    标题("【5】批量：一次请求算多段文字")
    批次 = [
        "改动任何文件前必须先落实改前恢复点。",
        "变更治理流程：改前恢复点 → 候选 → 复核 → 报告 → 确认 → 发布 → 回读。",
        "接口测试用例按 P0/P1/P2 分级。",
        "今天西安天气多云转晴。",
    ]
    for i, t in enumerate(批次, 1):
        print(f"    {i}. {t}")
    t0 = time.time()
    vs = 向量化.向量化(批次, 场景="演示_批量")
    耗时 = time.time() - t0
    print(f"\n    返回 {len(vs)} 个向量，每个 {len(vs[0])} 维，耗时 {耗时:.2f} 秒")
    if 向量化.缓存实例().本次命中:
        print(f"    （其中 {向量化.缓存实例().本次命中} 条命中了缓存，没有重新计算）")

    # ---------- 5. 语义相似度（用正确的余弦） ----------
    标题("【6】关键：这些数字真的能表达「意思相近」吗")
    S = 余弦相似度矩阵(vs)
    标签 = ["A 恢复点", "B 变更流程", "C 接口用例", "D 天气"]
    print("\n    余弦相似度矩阵（归一化后计算；越接近 1 越像）：\n")
    print("    " + "".join(f"{l:>14}" for l in 标签))
    for i, li in enumerate(标签):
        print(f"    {li:>11}" + "".join(f"{S[i][j]:>14.4f}" for j in range(4)))

    print(f"""
    怎么看：
        对角线现在都是 1.0000 —— 因为做了归一化，自己和自己必然是 1。这是基准线。
        A↔B = {S[0][1]:.4f}  最高 —— 两段都在讲"变更治理"，语义最近 ✅
        A↔C = {S[0][2]:.4f}  中等 —— 同属工程规则领域，但不同题
        A↔D = {S[0][3]:.4f}  最低 —— 一个讲规则、一个讲天气，完全无关 ✅

    ★ 对比一下：如果不归一化，对角线会显示 {模长:.4f}² = {模长**2:.4f} 而不是 1，
      所有数值都被整体压低，看起来像"都不太像"，容易误判。
      这就是为什么必须先归一化。
""")

    # ---------- 6. 检索 ----------
    print("【7】实际检索：用问题去找资料（措辞和原文不一样，看能不能找对）")
    问题 = "改文件之前要先做什么"
    print(f"    提问：「{问题}」")
    qv = 向量化.向量化单条(问题, 场景="演示_检索")
    分 = 归一化(qv) @ 归一化(np.asarray(vs, dtype=np.float32)).T
    排序 = sorted(zip(分.tolist(), 标签), reverse=True)
    for rank, (s, lb) in enumerate(排序, 1):
        print(f"        {rank}. {lb:<12} {s:.4f}")
    print(f"""
    期望第 1 名：A 恢复点（资料原文写的是"改动任何文件前必须先落实改前恢复点"）
    实际第 1 名：{排序[0][1]}
    结果：{'✅ 找对了' if 排序[0][1].startswith('A') else '❌ 没找对'}

    注意：问题里根本没有"恢复点"三个字，用的是"改文件之前"。
    关键词搜索在这里会失败；embedding 比的是"意思"，所以能找到。
    这就是 RAG 能成立的根本原因。
""")

    # ---------- 7. 成本 ----------
    标题("【8】本次花了多少钱（真实用量，不是估的）")
    账 = 向量化.读账本()
    print(f"    账本位置   : {向量化.账本路径}")
    print(f"    累计调用   : {账['次数']} 次")
    print(f"    累计 token : {账['tokens']}")
    print(f"    累计费用   : {账['费用_元']} 元")
    print(f"""
    怎么算的：费用 = token 数 ÷ 1,000,000 × 0.5 元（智谱 embedding-3 单价）
    全量语料约 309 万字符 ≈ 251 万 token ≈ 1.3 元。
    日常提问几乎不花钱——问题很短，一次十几个 token。

    ★ 注意"累计调用次数"这个数：它只统计**真正调了接口**的次数。
      命中缓存的不计费、也不出现在这里。
""")

    标题("第 0.5 步完成")
    print("""
    你现在已经亲眼看到：
      ① 文字变成 1024 个数字；这些数字均值≈0、模长 0.78（★不是 1，所以必须自己归一化）
      ② 归一化之后，自己和自己相似度=1，数值才能按 0~1 解释
      ③ 重复调用走本地缓存：不调接口、不花钱、耗时从 0.5 秒降到毫秒级
      ④ 批量比单条快得多（网络往返被摊薄）
      ⑤ 意思近的文字，向量也近
      ⑥ 问"改文件之前要做什么"，能找到写着"改动任何文件前必须先落实改前恢复点"的资料
      ⑦ 每一步花了多少 token、多少钱，账本里都是真数
""")
    return 0


if __name__ == "__main__":
    sys.exit(主流程())
