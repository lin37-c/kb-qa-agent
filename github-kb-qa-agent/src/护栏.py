def 自检() -> dict:
    """可被验证脚本调用的结构性自证（判据来自**源码本身**，不是自述）。

    它证伪的是这件事：**本模块里是否存在"强制放行"的写法**。

    ★ 判据口径（2026-10-14 第一版写错过，如实留痕）：
      第一版直接对**整个文件文本**做正则匹配，结果把**注释里解释"本模块没有强制放行"的那句
      话本身**匹配上了 → 自检报"存在强制放行写法：True"，是**假阳性**。
      教训与 F-17 同型：**给检查工具定的扫描范围，会把检查工具自己的措辞也算进去**。
      现改为：用 `tokenize` **去掉注释与字符串字面量**，只对**可执行代码**判定。
    """
    import io
    import tokenize
    源 = Path(__file__).read_text(encoding="utf-8")

    代码段 = []
    try:
        for tok in tokenize.generate_tokens(io.StringIO(源).readline):
            if tok.type in (tokenize.COMMENT, tokenize.STRING):
                continue
            代码段.append(tok.string)
    except tokenize.TokenError:
        return {"自检失败": "源码无法分词", "存在强制放行写法": True}
    代码 = " ".join(代码段)

    禁词 = [r"\boverride\b", r"\bforce\b\s*=", r"skip_guard", r"bypass",
            r"强制放行", r"allow_any", r"no_check"]
    命中 = [w for w in 禁词 if re.search(w, 代码, re.I)]
    return {
        "扫描口径": "去注释与字符串后的可执行代码（tokenize）",
        "存在强制放行写法": bool(命中),
        "命中禁词": 命中,
        "拦截出口数": 代码.count("raise 拦截"),
        "判定函数": "检查操作",
        "写入类工具": [k for k, v in 工具检查表.items() if "路径归属" in v],
    }


