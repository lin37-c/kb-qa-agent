def 路径归属(路径: str | os.PathLike, 解析符号链接: bool = True) -> dict:
    """判断一个写入目标属于哪一类区域。返回 {类别, 绝对路径, 说明}。

    类别取值（这四类是"正式区"这个词在本项目里的真实含义）：
        只读来源   —— 资产包，任何写入都拒
        候选区     —— 本项目写入的合法前置区，允许写
        恢复点     —— 恢复点目录，允许写（它本身就是回退依据）
        运行产物   —— data\\ 与 05_项目验证证据\\，允许写
        正式区     —— 项目其余部分，只能走 发布()
        区外       —— 以上都不在，按 P-02 需显式声明

    ★ `解析符号链接=False` 的用途（2026-10-14 实测踩到才加）：
        默认用 `resolve()` 把路径**落到真实位置**再比 —— 但 `resolve()` 对
        **还不存在的路径**会返回一个"尽力而为"的规范化结果，实测把
        `恢复点\\<新恢复点名>\\文件副本` 判成了**区外**（因为它还不存在，
        解析后落到了盘符根部），于是"落恢复点"这个工具反而被自己的护栏拦住。
        需要判定"**将来会写到哪里**"的场合（新建恢复点）应改用词法比较（不解析符号链接）。
    """
    p = Path(路径)
    try:
        ap = p.resolve() if 解析符号链接 else Path(os.path.normpath(os.path.abspath(str(p))))
    except OSError:
        ap = Path(os.path.abspath(str(p)))

    def 在下(根: Path) -> bool:
        try:
            if 解析符号链接:
                ap.relative_to(根.resolve())
            else:
                # 词法比较：不解析符号链接，允许目标尚不存在
                a = os.path.normcase(os.path.normpath(str(ap)))
                b = os.path.normcase(os.path.normpath(str(根)))
                if not a.startswith(b.rstrip("\\/") + os.sep) and a != b:
                    raise ValueError
            return True
        except (ValueError, OSError):
            return False

    if 在下(资产包根):
        return {"类别": "只读来源", "绝对路径": str(ap),
                "说明": f"资产包（{资产包根}）只读；本项目只产出派生索引，不改动它一个字节"}
    if 在下(候选区根):
        return {"类别": "候选区", "绝对路径": str(ap), "说明": "候选区：本项目写入的合法前置区"}
    if 在下(恢复点根):
        return {"类别": "恢复点", "绝对路径": str(ap), "说明": "恢复点目录：回退依据，允许写"}
    if 在下(项目根):
        rel = ap.relative_to(项目根.resolve())
        头 = rel.parts[0] if rel.parts else ""
        if 头 in _运行产物相对:
            return {"类别": "运行产物", "绝对路径": str(ap),
                    "说明": f"运行产物区（{头}\\）：过程输出，允许直写"}
        if 头 in _正式区免检:
            return {"类别": "运行产物", "绝对路径": str(ap), "说明": f"{头}\\：非交付内容"}
        return {"类别": "正式区", "绝对路径": str(ap),
                "说明": "项目正式区：工具不得直写，须走候选 → 发布流程"}
    return {"类别": "区外", "绝对路径": str(ap),
            "说明": f"不在已登记的任何区域内（会话工作区 {会话工作区}）"}


