class 拦截(Exception):
    """护栏拦截：抛出即终止，**没有放行出口**。

    带结构化字段，便于上层把它原样回灌给模型（让它知道"为什么不能做、该怎么改"），
    也便于审计记录逐条追溯。
    """

    def __init__(self, 违规: list[dict]):
        self.违规 = 违规
        super().__init__("；".join(f"[{v['规则']}] {v['判据']}" for v in 违规))


def _像是已解析的绝对路径(s: str) -> bool:
    """判断调用方给的"路径"是不是**已经解析好的绝对落点**（而不是候选区相对写法）。

    ★ 为什么需要这个区分（2026-10-14 第二处假阳性，如实留痕）：
      `工具.调用()` 的契约是"护栏负责解析，工具拿解析后的绝对路径去落盘"，
      所以它调 `检查操作` 时传的**已经是绝对路径**。
      而 `解析写路径()` 会把绝对路径判为违规（防"当成相对路径拼出怪路径"）——
      于是**正常的新建文件也被拒**（探针② 实测：本该放行却返回"拒"）。
      **假阳性比漏拦更难发现**：它看起来"更安全"，实际上让护栏把正常工作卡死了。
      判法：盘上存在的路径可 resolve；`盘符:` 开头或 UNC 开头即为绝对写法。
    """
    if re.match(r"^[A-Za-z]:[\\/]", s) or s.startswith("\\\\"):
        return True
    try:
        return Path(s).is_absolute() and Path(s).exists()
    except OSError:
        return False


def 解析写路径(路径: str | os.PathLike) -> str:
    """把「候选区相对路径」解析成**绝对路径**。写类工具路径的唯一解析入口。

    ★ 为什么解析放在护栏里（2026-10-14 实测踩到后改的，如实留痕）：
      第一版把解析放在 `工具._写路径()`，由 `工具.调用()` 在**调用护栏之前**先跑一遍。
      后果有二：
        ① 解析失败（`..` 跳出、绝对路径）时**在护栏之外就抛了**——
           既没有走判定、**也没有进审计日志**（试跑实测：探针③被拒，但审计行数 +0）。
           而"被拦住的动作必须留痕"恰恰是护栏存在的意义之一。
        ② 同一个路径被解析两次（工具一次、护栏判据又一次），**两处口径可能漂移**。
      修法：解析移进护栏，`检查操作()` 里调用它，并把解析结果写进判定记录。
      这样每一次写类调用都留下"它到底要写到哪"的证据 —— 判据与证据同源。

    两条拒绝（结构上不给绕，不靠调用方自觉）：
      · `..` 跳出 —— 否则可以 `..\\..\\项目\\02_项目源码与工程\\src\\工具.py` 直写正式区
      · **绝对路径（原始写法）** —— 若把它当相对路径拼到候选区下，会得到
        `<候选区>\\<盘符>\\x\\工具.py` 这种**怪路径**：护栏判成"在候选区内"就放行，
        而落盘位置完全不是调用方以为的地方。**判据错了比不做检查更糟**（P-08 第 5 款）。
        （注意：`工具.调用()` 传进来的"已解析绝对路径"走 `_像是已解析的绝对路径()`
          分支，不进这里 —— 两件事不要混。）
    """
    s = str(路径).replace("\\", "/")
    p = PurePosixPath(s)
    if p.is_absolute() or re.match(r"^[A-Za-z]:", s) or any(部 == ".." for 部 in p.parts):
        raise 拦截([{"规则": "P-14", "判据": "候选区路径不接受绝对路径或 .. 跳出",
                    "证据": str(路径),
                    "修法": "改用候选区内的相对路径，如 工具.py 或 子目录\\文件.md"}])
    return str(候选区根 / Path(*p.parts))


def 检查操作(工具名: str, 参数: dict, 声明: dict | None = None) -> dict:
    """工具调用前的护栏检查。通过返回判定记录；不通过抛 `拦截`。

    参数
        工具名 : 必须已登记在 工具检查表 中
        参数   : 工具的实际参数（判定直接读它，不做任何"看起来像"的推断）
        声明   : 本次调用的会话声明，如 {"allow_overwrite": True}
    """
    声明 = 声明 or {}
    违规: list[dict] = []
    检查过: list[str] = []
    解析后 = None
    # ★ 写类工具：先解析目标，**解析失败也算一次拦截并留痕**（不在护栏之外抛）
    #   注意"已经解析过"的情况：`工具.调用()` 会先把目标解析成绝对路径再调这里
    #   （护栏的路径判据必须看到真实落点，不能看相对写法）。所以这里要区分
    #   「调用方给的原始写法」与「已解析好的绝对路径」——
    #   第一版没区分，结果**探针②（新建文件的正常路径）被自己的解析判据拒掉**，
    #   属假阳性：护栏把正常工作也拦了（比漏拦更难发现，因为它看起来"很安全"）。
    #   ★ 门条件（2026-10-14 第三次修正，如实留痕）：
    #     第一版是 `if "路径归属" in 工具检查表[工具名]` ——
    #     而 `记一件`／`追加账本` 用的检查项是 **`登记处白名单`**（不是"路径归属"），
    #     于是**它们根本不进这个解析分支**：`解析后` 永远是 None，
    #     白名单判据永远说"未能确定写入落点"→ **永远拒**。
    #     教训与 F-21 同型：**判据的"入口条件"也是判据的一部分** ——
    #     只改判据内容、忘了改"什么时候跑这条判据"，等于没改。
    _需路径类检查 = {"路径归属", "登记处白名单"}
    if _需路径类检查 & set(工具检查表.get(工具名, [])):
        检查过.append("路径解析")
        原样 = str(参数.get("路径", ""))
        # "目标根 ＋ 范围"形式的工具（如 落恢复点）**没有「路径」参数** ——
        # 它的写入落点是**代码决定的**（恢复点目录），所以路径归属要判**落点**而不是"目标根"。
        # ★ 这一点实测踩到过（2026-10-14）：第一版把「目标根」（项目正式区）当判定对象，
        #   于是"落恢复点"这个**专门用来提供回退依据**的工具被自己的护栏拦住了 ——
        #   判据看错了对象：**它读目标根、写恢复点**，该判的是后者。
        if not 原样 and 参数.get("目标根"):
            名称 = str(参数.get("名称") or "")
            解析后 = str(恢复点根 / 名称) if 名称 else None
        # ★ 登记处工具（S3）：落点也是**代码决定的**（四个固定登记处），签名里没有「路径」。
        #   这里把"这次会写到哪个文件"算出来交给白名单判据 ——
        #   判据必须看到**真实落点**，不能因为工具形状不同就跳过检查
        #   （否则"没写路径参数的写工具"就成了护栏盲区）。
        elif not 原样 and 工具名 in ("记一件", "追加账本"):
            落点 = 登记处[记一件落点.get(str(参数.get("类型", "")), "账本")]
            解析后 = str(落点)
        elif _像是已解析的绝对路径(原样):
            解析后 = 原样
        else:
            try:
                解析后 = 解析写路径(原样)
            except 拦截 as e:
                违规 += e.违规
    if os.environ.get("护栏_调试"):
        print(f"[护栏调试] 工具={工具名} 原样={原样!r} "
              f"像已解析={_像是已解析的绝对路径(原样)} 解析后={解析后!r} "
              f"至此违规={[v['规则'] for v in 违规]}", file=sys.stderr)
    for 项 in 工具检查表.get(工具名, ["工具白名单"]):
        检查过.append(项)
        本项 = _跑检查(项, 工具名, 参数, 声明, 解析后)
        if os.environ.get("护栏_调试"):
            print(f"[护栏调试] 检查项={项} 产出违规={[v['规则'] for v in 本项]}", file=sys.stderr)
        违规 += 本项
    if os.environ.get("护栏_调试"):
        print(f"[护栏调试] 工具={工具名} 原样={原样!r} "
              f"像已解析={_像是已解析的绝对路径(原样)} 解析后={解析后!r}", file=sys.stderr)

    记录 = {
        "时间": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "工具": 工具名,
        "参数摘要": _参数摘要(参数),
        "解析后路径": 解析后,
        "检查项": 检查过,
        "判定": "拦截" if 违规 else "放行",
        "违规": 违规,
        "敏感模式集": sorted(敏感模式) if "敏感内容" in 检查过 else None,
    }
    落审计(记录)
    if 违规:
        raise 拦截(违规)
    return 记录


def _跑检查(项: str, 工具名: str, 参数: dict, 声明: dict,
            解析后: str | None = None) -> list[dict]:
    """跑一个检查项。★ **一切路径类判据都必须用「解析后的绝对落点」**。

    踩过的坑（2026-10-14，本阶段第三处假阴性，如实留痕）：
      `路径归属` 用了 `解析后`，而 `恢复点` 与 `覆盖确认` 第一版仍读 `参数["路径"]`。
      偏偏 `工具.调用()` 会**先**用原始相对路径调一次护栏，于是：
        `Path("授权记录.md").exists()` → False（相对当前工作目录，盘上根本没这个文件）
        → 判定"这是新建文件、不需要恢复点" → **P-12 静默放行**。
      症状具有欺骗性：探针①期望"拒"却得到"放行"，看起来像"护栏能力不够"，
      实际是**判据读了未经解析的路径**。统一用 `解析后` 后即恢复正常。
      教训：**同一类判据（都用路径）必须共用同一个取值口径**，
      否则"哪一项忘了改"这种漏洞会以"看起来正常的判定"形式存活。
    """
    目标路径 = 解析后 or 参数.get("路径")

    if 项 == "工具白名单":
        if 工具名 not in 工具检查表:
            return [{"规则": "工具白名单", "判据": f"未登记的工具：{工具名}", "证据": ""}]
        return []

    if 项 == "参数合法":
        return []   # schema 校验在 工具.py 的执行入口做，判定层不重复

    if 项 == "路径归属":
        目标 = 目标路径
        if not 目标:
            return [{"规则": "P-14", "判据": "写类工具缺「路径」参数，无法判定归属", "证据": ""}]
        归 = 路径归属(目标)
        类 = 归["类别"]
        # 恢复点目录里的**尚不存在**的子路径要按"将来会写到哪"判（词法比较），
        # 否则新建恢复点会被判成"区外"（2026-10-14 实测）。
        if 类 == "区外":
            归2 = 路径归属(目标, 解析符号链接=False)
            if 归2["类别"] != "区外":
                归, 类 = 归2, 归2["类别"]
        if 类 == "只读来源":
            return [{"规则": "P-14", "判据": "目标在资产包内，资产包只读",
                     "证据": f"{归['绝对路径']}", "修法": "本项目只产出派生索引，不改资产包；如确需改，走资产包维护事务"}]
        if 类 == "正式区":
            return [{"规则": "P-14", "判据": "目标在项目正式区，工具不得直写",
                     "证据": f"{归['绝对路径']}",
                     "修法": "先写候选区（候选_LLM知识库检索与工具调用_20261013），再走 发布()"}]
        if 类 == "区外":
            return [{"规则": "P-02", "判据": "目标不在已登记的任何区域内",
                     "证据": f"{归['绝对路径']}",
                     "修法": "该路径不在本任务改动面内；如确需改，请用户单独授权后再登记区域"}]
        return []

    if 项 == "恢复点":
        目标 = 目标路径          # ★ 必须是解析后的绝对落点，否则 exists() 会误判为"新建"
        if not 目标:
            return []
        p = Path(目标)
        if not p.exists():
            # ★ 新建文件：删掉即回到零，不产生不可回退的损失 → 不需要改前恢复点
            return []
        已 = 已有恢复点(p)
        if 已 is None:
            return [{"规则": "P-12", "判据": "目标文件已存在（覆盖会丢内容）但查无恢复点副本",
                     "证据": f"{p}",
                     "修法": "先落改前恢复点（逐字节副本 ＋ 逐文件 sha256 ＋ 当场回读）再覆盖"}]
        return []

    if 项 == "敏感内容":
        文 = 参数.get("内容") or ""
        命 = 扫敏感内容(文)
        if 命:
            return [{"规则": "P-01", "判据": "写入内容命中敏感模式",
                     "证据": "；".join(f"{x['模式']}→{x['片段']}" for x in 命),
                     "修法": "移除或脱敏后再写入；密钥只从环境变量读，绝不落盘"}]
        return []

    if 项 == "破坏性":
        if 参数.get("destructive") and not 声明.get("allow_destructive"):
            return [{"规则": "P-10", "判据": "破坏性动作未取得显式授权",
                     "证据": f"{参数.get('路径', '')}",
                     "修法": "先向用户逐项报清单并取得确认，再带 allow_destructive 调用"}]
        return []

    if 项 == "覆盖确认":
        目标 = 目标路径          # ★ 同上：必须用解析后的绝对落点
        if not 目标 or not Path(目标).exists():
            return []
        if not 声明.get("allow_overwrite"):
            return [{"规则": "P-12", "判据": "目标文件已存在：覆盖前需显式声明 allow_overwrite",
                     "证据": f"{目标}",
                     "修法": "确认这个文件是要覆盖的那一份（候选区可能有上一轮的待发布件）；"
                             "确认后带 allow_overwrite=True 重调"}]
        return []

    if 项 == "恢复点目标":
        # 形式：参数里有「目标根」＋「范围」列表。逐条解析范围，确认都在目标根之内。
        根 = 参数.get("目标根")
        if not 根:
            return [{"规则": "P-12", "判据": "缺「目标根」参数，无法判定范围边界", "证据": ""}]
        基 = Path(根)
        if not 基.is_absolute():
            基 = 项目根 / 基
        违规 = []
        for r in (参数.get("范围") or []):
            s = str(r)
            if re.match(r"^[A-Za-z]:[\\/]", s) or s.startswith("\\\\") or Path(s).is_absolute():
                违规.append({"规则": "P-12", "判据": "范围里出现绝对路径（应从目标根出发写相对路径）",
                           "证据": s, "修法": "改用相对「目标根」的路径"})
                continue
            if any(部 == ".." for 部 in re.split(r"[\\/]", s)):
                违规.append({"规则": "P-12", "判据": "范围里出现 `..`（可能跳出目标根）",
                           "证据": s, "修法": "改用目标根内的相对路径"})
        return 违规

    if 项 == "登记处白名单":
        # 只允许写这四个登记处（＋账本）；**其它任何路径一律拒**——
        # 这样"例外"是窄的：登记类工具**不可能**被用来改别的正式文件。
        允许 = {str(p) for p in 登记处.values()}
        # ★ 取值口径（2026-10-14 实测踩到，如实留痕）：
        #   第一版写的是 `参数.get("解析后路径") or 解析后` ——
        #   **`解析后路径` 是我稍后要写进「判定记录」的键，此刻还没生成**，
        #   于是永远取到 None，整条白名单判据变成"永远判定不出落点 → 永远拒"。
        #   教训与 F-21 同型：**取值口径必须取"生产实际算出来的那个值"**，
        #   不能取"我以为已经在参数里的那个键"。
        目标 = 解析后
        if not 目标:
            return [{"规则": "P-14", "判据": "登记类工具未能确定写入落点（视为不放行）", "证据": ""}]
        if str(目标) not in 允许:
            return [{"规则": "P-14",
                     "判据": "登记类工具只能写四个固定登记处（需求文档／素材库／成果表／未决表／账本）",
                     "证据": str(目标),
                     "修法": "要改别的正式文件请走候选 → 发布流程（发布需用户口令）"}]
        return []

    return [{"规则": "护栏自身", "判据": f"未知检查项 {项}（视为不放行）", "证据": ""}]


def _参数摘要(参数: dict) -> dict:
    """审计记录用的参数摘要：长文本只留长度与指纹，不整段落盘。"""
    摘 = {}
    for k, v in (参数 or {}).items():
        if isinstance(v, str) and len(v) > 120:
            摘[k] = f"<{len(v)} 字符，sha256:{hashlib.sha256(v.encode('utf-8')).hexdigest()[:16]}>"
        else:
            摘[k] = v
    return 摘


