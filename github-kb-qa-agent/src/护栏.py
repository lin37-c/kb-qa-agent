def _载入恢复点清单() -> tuple[dict[str, dict], list[str]]:
    """扫盘收集"哪些文件已有恢复点副本"。返回（{原件绝对路径: 信息}, 解析失败的清单）。

    ★ 必须兼容**两种清单格式**（2026-10-14 实测踩到，如实留痕）：
        旧格式（本任务之前建立的 14 份）：
            键 = 目标／恢复点／建立时间／依据／目的／口径／文件数／总字节／文件清单
            `文件清单[i].path` 是**副本的绝对路径**（在恢复点目录里），原件位置要靠
            「目标」＋ 副本相对路径推算
        新格式（本任务 `落恢复点_M5.py` 建立的）：
            键 = 恢复点名称／建立时间／项目根／范围／排除目录／文件数／总字节／文件
            `文件[i].相对路径` 是**相对项目根**的路径
    第一版只认新格式，对旧格式直接 `TypeError` 崩掉 —— 而"崩掉"比"判错"好一点，
    但仍然是**判据没覆盖真实数据**。修法不是"跳过旧格式"（那会让护栏看不见历史恢复点），
    而是两种都读。
    """
    条目: dict[str, dict] = {}
    跳过: list[str] = []
    if not 恢复点根.exists():
        return 条目, 跳过
    for 清单 in sorted(恢复点根.glob("*/基线清单.json")):
        try:
            # utf-8-sig：旧清单带 BOM，用 utf-8 读会直接 JSONDecodeError
            数据 = json.loads(清单.read_text(encoding="utf-8-sig"))
        except Exception as e:  # noqa: BLE001
            跳过.append(f"{清单.parent.name}（清单无法解析：{type(e).__name__}）")
            continue
        名 = 清单.parent.name

        def 记(原件: Path, sha: str, 字节, 来源: str) -> None:
            try:
                键 = str(原件.resolve())
            except OSError:
                键 = str(原件)
            条目.setdefault(键, {"恢复点": 名, "sha256": sha, "字节": 字节, "来源": 来源})

        # 新格式：文件[i].相对路径
        for 条 in (数据.get("文件") or []):
            if isinstance(条, dict) and 条.get("相对路径"):
                记(Path(数据.get("项目根", "")) / 条["相对路径"],
                  条.get("sha256", ""), 条.get("字节"), "文件[]")
        # 旧格式：文件清单[i].path（副本绝对路径 → 反推原件相对路径）
        for 条 in (数据.get("文件清单") or []):
            if not isinstance(条, dict):
                continue
            副 = 条.get("path") or ""
            目标 = 数据.get("目标") or ""
            if not 副 or not 目标:
                continue
            try:
                相对 = Path(副).relative_to(清单.parent / "文件副本")
            except ValueError:
                # 副本不在标准位置时退回用文件名补齐
                相对 = Path(条.get("newName") or Path(副).name)
            记(Path(目标) / 相对, 条.get("sha256", ""), 条.get("size"), "文件清单[]")
    return 条目, 跳过


def 已有恢复点(路径: str | os.PathLike, 用缓存: bool = True) -> dict | None:
    """查这个路径是否已有恢复点副本。有则返回那份恢复点的信息，无则 None。

    判据来源：恢复点目录下的 `基线清单.json`（**两种格式都读**）。
    **扫盘查，不查任何自建登记** —— 登记表会与盘上事实脱节（P-08 第 1 款）。

    ⚠️ 语义边界（如实写明，别把它当更强的判据用）：
        本函数回答的是「**这个路径在某个恢复点里有没有副本**」，
        **不回答**「那份副本是不是这个路径的*当前*内容」。
        因此它能强力支持 P-12 的"覆盖前要有可回退副本"，
        但**不构成** P-08 意义上"基线一致"的证明 —— 那要另做逐字节比对。
    """
    try:
        ap = Path(路径).resolve()
    except OSError:
        ap = Path(os.path.abspath(str(路径)))
    键 = str(ap)
    if 用缓存 and _恢复点清单缓存["条目"] is not None:
        return _恢复点清单缓存["条目"].get(键)
    条目, 跳过 = _载入恢复点清单()
    _恢复点清单缓存.update({"条目": 条目, "跳过": 跳过})
    return 条目.get(键)


def 文件指纹(路径: str | os.PathLike) -> str:
    p = Path(路径)
    if not p.is_file():
        return ""
    h = hashlib.sha256()
    with p.open("rb") as f:
        for 块 in iter(lambda: f.read(1 << 20), b""):
            h.update(块)
    return h.hexdigest()


