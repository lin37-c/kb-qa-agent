"""S2｜发布与口令：把「候选 → 四项确认 → 用户口令 → 发布 → 回读」做成可调用能力。

==========================================================================
★ 本模块最重要的设计：**口令闸门**（为什么它必须是这个形状）
==========================================================================
`发布()` 是全项目**唯一能写进正式交付物**的动作。风险不对称：
    · 写候选区错了 → 删掉重来，代价 0；
    · 写正式区错了 → 已发布的东西被污染，代价不可逆。
所以《禁令》**P-10 第 8 款**明确：「**『按规则走 X』不等于授权执行 X**」，
发布必须由**用户当次明确放行**；`维护规则` §6.2④ 也要求"报告与过目是口令的前置条件"。

**天真的做法**：给 `发布()` 加一个 `口令` 参数，让**模型**填。
**为什么不行**：参数由模型生成 = **授权由模型给出**，等于把 P-10 的闸门交给被约束的对象自己。
模型只要填一个字符串就能发布，"闸门"就只剩装饰。

**本模块的做法**（三条，缺一不可）：

    ① **口令由程序侧生成**（`发行口令()`），**只由人类侧持有**；
       模型即使被要求"发布"，也拿不到口令 —— 它只能`生成发布计划()`。
    ② **口令不是通用钥匙，而是"授权书"**：绑定 **(候选路径, 目标路径)** 这一对；
       换一个目标、换一批文件，旧口令**校验不过**。
    ③ **一次性 ＋ 过期**：用过即作废（防重放）；超过 `口令有效期秒` 自动失效。

    口令存盘位置：`04_项目工作过程\\发布口令.json`（**项目内**，模型可读）——
    这一点的取舍写在 `发行口令()` 的注释里，**不假装它不可读**。

==========================================================================
与 §6.2 七步流程的对应
==========================================================================
    ①改前恢复点 → 由 `落恢复点` 工具负责（S1）
    ②候选先行   → 由 `写候选` 工具负责
    ③四项确认   → 由**调用方**在计划里逐项声明（本模块只校验"声明齐不齐"，
                   **不代替人做判断** —— 那是智能体与用户的活儿）
    ④报告义务   → 生成计划时逐文件列出"候选哈希 → 目标现状"，供人过目
    ⑤用户确认   → ★ **口令**
    ⑥发布＋回读 → 复制后**逐文件重算哈希**与计划比对；不一致即判失败
    ⑦清理候选   → **本模块不做**（P-12 第 4 款：不得以"使命已尽"为名提前删）
"""
