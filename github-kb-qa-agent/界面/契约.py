# -*- coding: utf-8 -*-
"""契约层：`生成.回答()` 的原始结果 → 界面消息模型（界面契约 v1.1）。

为什么单独一层：
    界面契约与生产链路是两件会各自演进的东西。把它们钉在**一个转换点**上，
    改界面不用动检索，改检索不用动界面；M9 的服务化也复用这一层。

本层做的四件事（都不是"顺手"，契约里有对应条款）：
    ① 20 个输出键 → 界面字段（缺一个前端就在运行时才炸）；
    ② `出处` 与 `命中` 按序号合并，补上重排分／重排前位次（`出处` 本身没有分数）；
    ③ `出处提取失败` 时把 `未采用` 置空 —— 生产返回在这条分支上两边是同一批材料；
    ④ 耗时的拆分：单次调用路径拿不到"检索 vs 生成"，检索＝总−生成（**间接**，第 4 步钩子改为实测）。
"""
from __future__ import annotations

from datetime import datetime

import 高危

# 契约 v1.1：`分组来源`／`候选池` 单次调用路径不可得（要 `检索()` 的返回才有），
# 因此标为可选；流式钩子路径（第 4 步）会补上。


def 拆行号(行号) -> tuple[int, int]:
    """`71–79` → (71, 79)。分隔符兼容 en dash／em dash／连字符／波浪号。"""
    s = str(行号 or "").strip()
    for 分隔 in ("–", "—", "-", "~", "…"):
        if 分隔 in s:
            左, _, 右 = s.partition(分隔)
            try:
                return int(左.strip()), int(右.strip())
            except ValueError:
                break
    return 0, 0


def 解析编号(编号) -> int:
    """`材料 3` → 3；已是数字则原样。"""
    s = str(编号 or "")
    数字 = "".join(ch for ch in s if ch.isdigit())
    return int(数字) if 数字 else 0


def _按命中补分(条目: dict, 命中: list[dict]) -> dict:
    """`出处` 里没有分数，从同序号的 `命中` 里合并重排分与重排前位次。"""
    编号 = 解析编号(条目.get("编号"))
    h = 命中[编号 - 1] if 0 < 编号 <= len(命中) else {}
    return {
        "编号": 编号,
        "来源文件": 条目.get("来源文件", ""),
        "标题路径": 条目.get("标题路径", ""),
        "行号": 条目.get("行号", ""),
        "起始行": 拆行号(条目.get("行号"))[0],
        "结束行": 拆行号(条目.get("行号"))[1],
        "相似度": 条目.get("相似度"),
        "重排分": h.get("重排分"),
        "重排前位次": h.get("重排前位次"),
        "内容指纹": 条目.get("内容指纹", ""),
        "被引用": bool(条目.get("被引用")),
        # ★ 第 8 步加：块正文随消息落盘。服务重启后旧消息仍能取原文——
        #   否则任务表在内存、一重启就 "取不到这段原文"（人工验收实测撞到）。
        "文本": h.get("文本", ""),
    }


def _命中条目(序号: int, h: dict) -> dict:
    """拒答时"最接近的 N 段"来自 `命中`（没有 `行号` 字符串，自己拼）。"""
    起 = int(h.get("起始行") or 0)
    止 = int(h.get("结束行") or 0)
    return {
        "编号": 序号,
        "来源文件": h.get("来源文件", ""),
        "标题路径": h.get("标题路径", ""),
        "行号": f"{起}–{止}",
        "起始行": 起,
        "结束行": 止,
        "相似度": h.get("相似度"),
        "重排分": h.get("重排分"),
        "重排前位次": h.get("重排前位次"),
        "内容指纹": h.get("内容指纹", ""),
        "被引用": False,
        "文本": h.get("文本", ""),
    }


def 档位视图(检索结果: dict) -> dict:
    """从 `检索()` 的返回直接建档位（第 4 步：检索一完成就能推给界面）。"""
    阈值 = 检索结果.get("闸门阈值") or {}
    return {
        "判定": 检索结果.get("判定", ""),
        "可作答": bool(检索结果.get("可否作答")),
        "闸门分": 检索结果.get("闸门分"),
        "闸门尺度": 检索结果.get("闸门尺度", ""),
        "阈值": {"高": 阈值.get("高"), "低": 阈值.get("低")},
        "分组": 检索结果.get("分组", ""),
        "分组来源": 检索结果.get("分组来源", ""),
        "查询扩展": list(检索结果.get("扩展词") or []),
        "召回条数": len(检索结果.get("结果") or []),
        "类型": "",
        "最高相似度": 检索结果.get("最高相似度"),
        "阈值说明": 检索结果.get("阈值说明", ""),
        "候选池": 检索结果.get("候选池"),
    }


def 候选出处(检索结果: dict) -> list[dict]:
    """召回到的全部材料（`被引用` 一律 False，答案生成后才知道引用了哪几段）。"""
    return [_命中条目(i, h) for i, h in enumerate(检索结果.get("结果") or [], 1)]


def 骨架消息(问题: str, 口径: dict, 检索结果: dict) -> dict:
    """`start` 事件用的半成品消息：档位与出处已就绪，答案还空着。"""
    return {
        "id": "",
        "角色": "assistant",
        "时间": datetime.now().isoformat(timespec="seconds"),
        "问题": 问题,
        "状态": "generating",
        "口径": 口径,
        "风险": 高危.识别(问题),
        "档位": 档位视图(检索结果),
        "答案": {"文本": "", "引用编号": [], "出处提取失败": False},
        "出处": 候选出处(检索结果),
        "未采用": [],
        "拒答": None,
        "用量": {},
        "耗时": {},
        "标注": None,
    }


def 转消息(原始: dict, 问题: str, 口径: dict, 总秒: float,
            检索结果: dict | None = None) -> dict:
    """唯一转换点。返回的 dict 即界面契约 §二 的助手消息。"""
    作答 = bool(原始.get("是否作答"))
    命中 = 原始.get("命中") or []
    阈值 = 原始.get("闸门阈值") or {}
    提取失败 = bool(原始.get("出处提取失败"))
    生成秒 = float((原始.get("用量") or {}).get("耗时秒") or 0.0)
    检索秒 = max(0.0, round(float(总秒) - 生成秒, 1)) if 总秒 else 0.0

    出处 = [_按命中补分(o, 命中) for o in (原始.get("出处") or [])]
    未采用 = [] if 提取失败 else [_按命中补分(o, 命中) for o in (原始.get("未采用") or [])]

    档位 = {
        "判定": 原始.get("检索判定", ""),
        "可作答": 作答,
        "闸门分": 原始.get("闸门分"),
        "闸门尺度": 原始.get("闸门尺度", ""),
        "阈值": {"高": 阈值.get("高"), "低": 阈值.get("低")},
        "分组": 原始.get("分组", ""),
        "分组来源": 原始.get("分组来源", ""),          # 单次调用路径为空；有检索结果时下面补
        "查询扩展": list(原始.get("查询扩展") or []),
        "召回条数": 原始.get("召回条数", 0),
        "类型": 原始.get("类型", ""),
        "最高相似度": 原始.get("最高相似度"),
        "阈值说明": 原始.get("阈值说明", ""),
        "候选池": None,
    }

    if 检索结果:
        # 第 4 步起有检索钩子，这两个字段终于有来源（契约 v1.1 的"可选"在这里被填满）
        档位["分组来源"] = 检索结果.get("分组来源", "") or 档位["分组来源"]
        档位["候选池"] = 检索结果.get("候选池")

    拒答 = None
    if not 作答:
        低 = float(阈值.get("低") or 0.0)
        分 = float(原始.get("闸门分") or 0.0)
        拒答 = {
            "原因": 原始.get("拒答原因", ""),
            "闸门分": 分,
            "阈值低": 低,
            "差": round(低 - 分, 4),
            "最接近": [_命中条目(i, h) for i, h in enumerate(命中[:3], 1)],
        }

    用量 = dict(原始.get("用量") or {})
    用量["是否返回"] = bool(用量)

    return {
        "id": "",                                        # 由路由按任务号填
        "角色": "assistant",
        "时间": datetime.now().isoformat(timespec="seconds"),
        "问题": 问题,
        "状态": "done" if 作答 else "refused",
        "口径": 口径,
        "风险": 高危.识别(问题),                                      # 高危识别在第 7 步接入
        "档位": 档位,
        "答案": {
            "文本": 原始.get("答案", ""),
            "引用编号": list(原始.get("引用编号") or []),
            "出处提取失败": 提取失败,
        },
        "出处": 出处,
        "未采用": 未采用,
        "拒答": 拒答,
        "用量": 用量,
        "耗时": {"检索": 检索秒, "生成": round(生成秒, 1), "总": round(float(总秒), 1)},
        "标注": None,
    }
