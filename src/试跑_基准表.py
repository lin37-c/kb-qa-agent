# 测哪些分组（不是全部组，否则太慢；这四个足以判断"该去哪一组"）
测的分组 = ["规则体系", "技能", "维护", "全库"]


def 期望排名(结果: dict, 前缀: str, 上限: int = 10):
    for i, h in enumerate(结果["结果"][:上限], 1):
        if h["来源文件"].startswith(前缀):
            return i
    return None


def 跑一轮(标签: str) -> dict:
    """跑一轮基准。

    ★ 2026-10-13 修口径（用户指出「统计结果也要对，不止是后端跑」）：
      原先只把「默认分组」的期望区排名当成判据 → 把技能类 6/7 误记成 3/7，
      因为默认分组是「规则体系」、本来就不含 01_技能。
      **判据改以「自动判房间」为准**（＝用户真实用法：不打前缀也不打房间名），
      默认分组保留为对照组（用来看"规则类有没有退化"）。

    ★ 同时修一个隐蔽 bug：`期望排名` 原先只在前 10 名里找，
      而检索返回的就是前 10 条 —— 若答案排在第 11 名之后，永远查不到、
      会被误记为"读不到"。现在取前 60 条来找排名（够宽，且不会拖慢太多）。
    """
    m, 元数据 = K.载入向量库()
    行 = []
    for i, (问题, 区域, 前缀) in enumerate(基准问题, 1):
        各组 = {}
        for g in 测的分组:
            try:
                r = R.检索(问题, 取前=10, 分组=g)
                各组[g] = {"最高分": r["最高相似度"], "期望排名": 期望排名(r, 前缀),
                          "候选池": r["候选池"]}
            except Exception as e:  # noqa: BLE001
                各组[g] = {"最高分": None, "期望排名": None, "候选池": 0, "错误": str(e)[:80]}
        # 对照组：默认分组（不打前缀、不自动判房间）
        try:
            rd = R.检索(问题, 取前=60)
            默认 = {"分组": rd["分组"], "最高分": rd["最高相似度"],
                   "期望排名": 期望排名(rd, 前缀, 上限=60), "判定": rd["判定"]}
        except Exception as e:  # noqa: BLE001
            默认 = {"分组": "?", "最高分": None, "期望排名": None, "判定": f"错误 {e}"[:80]}
        # ★ 主判据：自动判房间（用户真实用法）
        try:
            ra = R.检索(问题, 取前=60, 自动判房间=True)
            自动 = {"分组": ra["分组"], "来源": ra["分组来源"], "最高分": ra["最高相似度"],
                   "期望排名": 期望排名(ra, 前缀, 上限=60), "判定": ra["判定"]}
        except Exception as e:  # noqa: BLE001
            自动 = {"分组": "?", "来源": "?", "最高分": None, "期望排名": None, "错误": str(e)[:60]}
        行.append({"序号": i, "问题": 问题, "期望区域": 区域, "期望前缀": 前缀,
                   "默认": 默认, "自动判房间": 自动, "各分组": 各组})
        print(f"  [{i:>2}/{len(基准问题)}] {问题:<24} 主判据(自动 {自动['分组'][:14]}) "
              f"{自动['最高分']} 排名{自动['期望排名'] or '—'}  ｜ 对照(默认) {默认['最高分']} 排名{默认['期望排名'] or '—'}")
    return {"标签": 标签, "库总量": len(元数据), "分组": 测的分组, "行": 行,
            "口径": "主判据＝自动判房间；对照＝默认分组；期望排名在前 60 名内查找"}


def 打印表(结果: dict) -> None:
    print("\n" + "=" * 118)
    print(f"基准问题表 · 标签「{结果['标签']}」 ｜ 库总量 {结果['库总量']:,} 块")
    print("=" * 118)
    print(f"{'#':>3} {'问题':<24}{'期望区':<8}{'主判据:自动判房间':<22}{'对照:默认分组':<22}  判定(自动)")
    print(f"{'':>3} {'':<24}{'':<8}{'房间':<14}{'分/排名':<9}{'分/排名':<13}")
    print("-" * 118)
    主命中 = 对照命中 = 0
    for r in 结果["行"]:
        d, a = r["默认"], r["自动判房间"]
        dmax = f"{d['最高分']:.4f}" if d["最高分"] is not None else "—"
        amax = f"{a['最高分']:.4f}" if a["最高分"] is not None else "—"
        dran = str(d["期望排名"] or "—")
        aran = str(a["期望排名"] or "—")
        if a["期望排名"]:
            主命中 += 1
        if d["期望排名"]:
            对照命中 += 1
        print(f"{r['序号']:>3} {r['问题']:<24}{r['期望区域']:<8}"
              f"{a['分组'][:13]:<14}{amax+'/'+aran:<9}"
              f"{dmax+'/'+dran:<13}  {a.get('判定','')[:20]}")
    print("-" * 118)
    n = len(结果["行"])
    print(f"  ★ 主判据（自动判房间，＝用户真实用法）读到期望区: {主命中} / {n}")
    print(f"    对照组（默认分组，不打前缀也不判房间）读到期望区: {对照命中} / {n}")
    print(f"    口径: {结果.get('口径', '—')}")

    print("\n  各分组的期望区排名（看「该去哪一组找」）：")
    print(f"    {'问题':<24}" + "".join(f"{g:>12}" for g in 结果["分组"]))
    for r in 结果["行"]:
        cells = []
        for g in 结果["分组"]:
            v = r["各分组"].get(g, {})
            n = v.get("期望排名")
            m = v.get("最高分")
            cells.append(f"{(str(n)+'/'+format(m,'.4f')) if (n and m is not None) else (format(m,'.4f') if m is not None else '—'):>12}")
        print(f"    {r['问题']:<24}" + "".join(cells))


def 对比(标签A: str, 标签B: str) -> None:
    """两轮基准逐题对照。

    ★ 2026-10-13 修口径：判据字段从「默认」（默认分组）改为「自动判房间」
      —— 与 `跑一轮` 一致。默认分组数据仍打印出来供参考（看规则类是否退化）。
    """
    pa, pb = 输出目录 / f"基准_{标签A}.json", 输出目录 / f"基准_{标签B}.json"
    if not pa.exists() or not pb.exists():
        print(f"  ❌ 缺少文件：{pa.exists()=} {pb.exists()=}")
        return
    A = json.loads(pa.read_text(encoding="utf-8"))
    B = json.loads(pb.read_text(encoding="utf-8"))
    print("\n" + "=" * 132)
    print(f"基准对比：「{标签A}」→「{标签B}」   （判据＝自动判房间）")
    print("=" * 132)
    print(f"  库总量: {A['库总量']:,} → {B['库总量']:,} 块")
    print(f"\n  {'#':>3} {'问题':<24}{'旧分':>9}{'新分':>9}{'变化':>9}"
          f"{'旧排名':>7}{'新排名':>7}  {'去向(新)':<24}  结论")
    print("  " + "-" * 128)
    好 = 平 = 差 = 0
    for a, b in zip(A["行"], B["行"]):
        o, n = a["自动判房间"], b["自动判房间"]
        om = o["最高分"] or 0.0
        nm = n["最高分"] or 0.0
        变化 = nm - om
        oran, nran = o["期望排名"], n["期望排名"]
        if (oran is None) and nran:
            结论 = "★ 从读不到 → 读到"
            好 += 1
        elif oran and nran and nran < oran:
            结论 = "↑ 排名提升"; 好 += 1
        elif oran and nran and nran > oran:
            结论 = "↓ 排名下降"; 差 += 1
        elif oran and nran:
            结论 = "= 持平"; 平 += 1
        elif oran is None and nran is None:
            结论 = "= 仍未读到"; 平 += 1
        else:
            结论 = "? 变化"
        print(f"  {a['序号']:>3} {a['问题']:<24}{om:>9.4f}{nm:>9.4f}{变化:>+9.4f}"
              f"{str(oran or '—'):>7}{str(nran or '—'):>7}  {n['分组'][:22]:<24}  {结论}")
    print("  " + "-" * 128)
    print(f"  汇总: 变好 {好} ／ 持平 {平} ／ 变差 {差}")

    # 规则类是否退化（用默认分组看，因为规则类本来就该在默认组命中）
    print(f"\n  附：默认分组口径的得分变化（看规则类是否退化）")
    print(f"    {'#':>3} {'问题':<24}{'旧分':>9}{'新分':>9}{'变化':>9}{'旧排名':>7}{'新排名':>7}")
    for a, b in zip(A["行"], B["行"]):
        o, n = a["默认"], b["默认"]
        om = o["最高分"] or 0.0
        nm = n["最高分"] or 0.0
        print(f"    {a['序号']:>3} {a['问题']:<24}{om:>9.4f}{nm:>9.4f}{nm-om:>+9.4f}"
              f"{str(o['期望排名'] or '—'):>7}{str(n['期望排名'] or '—'):>7}")


def main() -> int:
    标签 = None
    if "--标签" in sys.argv:
        标签 = sys.argv[sys.argv.index("--标签") + 1]
    if "--对比" in sys.argv:
        i = sys.argv.index("--对比")
        对比(sys.argv[i + 1], sys.argv[i + 2])
        return 0

    print("=" * 118)
    print(f"基准问题表 ｜ 标签「{标签 or '临时'}」｜ 问题 {len(基准问题)} 条 × {len(测的分组)} 分组")
    print("=" * 118)
    结果 = 跑一轮(标签 or "临时")
    打印表(结果)

    if 标签:
        输出目录.mkdir(parents=True, exist_ok=True)
        out = 输出目录 / f"基准_{标签}.json"
        out.write_text(json.dumps(结果, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"\n  结果已写: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
