# -*- coding: utf-8 -*-
"""M4 试跑：验证生成层的四件事（带出处 / 不硬答 / 对比整合 / 成本）。

设计原则：**每段都写明"在验证什么、期望看到什么"**，不只报"跑通了"。

用法：
    python 试跑_生成.py            # 全部用例
    python 试跑_生成.py <问题>     # 单个问题
"""
from __future__ import annotations

import sys
from pathlib import Path

# 搜索路径两处：
#   ① 本文件目录 —— 命中"正在被验证的候选版 生成.py"
#   ② 正式位置 src\ —— 让 生成.py 里的 import 配置/向量化/缓存/入库/检索 命中已发布依赖
项目src = Path(r"<workspace>\01_项目\DeepSeek Harness专用\LLM知识库检索与工具调用\02_项目源码与工程\src")
for p in (str(Path(__file__).resolve().parent), str(项目src)):
    if p not in sys.path:
        sys.path.insert(0, p)

import 生成 as G


def 段(t: str) -> None:
    print("\n" + "=" * 78)
    print(t)
    print("=" * 78)


def 用例(问题: str, 验证点: str, 期望: str, 显示命中: int = 0) -> dict | None:
    print(f"\n【验证：{验证点}】")
    print(f"  期望：{期望}")
    try:
        r = G.回答(问题)
    except Exception as e:  # noqa: BLE001
        print(f"  ❌ 异常：{e}")
        return None
    print(G.格式化(r, 显示命中=显示命中))
    return r


def main() -> int:
    单问 = sys.argv[1] if len(sys.argv) > 1 else None
    if 单问:
        r = G.回答(单问)
        print(G.格式化(r, 显示命中=3))
        return 0

    print("=" * 78)
    print("M4 生成层试跑")
    print("=" * 78)
    print(f"对话模型: {G.对话模型}")
    print(f"温度    : 0（严格模式，答案可复现）")
    print(f"问题分类: 对比型召回 {G.取前条数('对比型')} 段 ／ 说明型 {G.取前条数('说明型')} ／ 事实型 {G.取前条数('事实型')}")
    print(f"检索阈值（临时，来自 M3）: 高 {G.R.阈值_高} ／ 低 {G.R.阈值_低}")

    # ---------- 验证① 带出处 ----------
    段("验证① 带出处：答案里每句要标〔材料 N〕，末尾另附出处清单")
    r1 = 用例(
        "改文件之前要先做什么",
        "带出处",
        "答案里出现〔材料 N〕标注；出处清单逐条列出来源文件＋标题路径＋行号",
        显示命中=2,
    )

    # ---------- 验证② 不硬答（P-07 落地） ----------
    段("验证② 不硬答：库里没有的问题必须明确说『没有』，不得用常识补")
    r2 = 用例(
        "今天西安的天气怎么样",
        "不硬答",
        "检索层判定为『库中没有相关内容』（最高分应远低于 0.53），直接拒答且**不调用模型**",
    )
    if r2:
        print(f"\n  复核：是否调用模型 = {'否（检索层拒答）' if not r2['是否作答'] else '是'} ｜ 用量 = {r2['用量'] or '无'}")

    # ---------- 验证③ 对比整合（F-6 的解法） ----------
    段("验证③ 对比型提问：材料里两件事是分开写的，模型要整合成对比")
    r3 = 用例(
        "候选区和正式区的区别是什么",
        "对比整合（F-6）",
        "M3 时此问题召不回（最高 0.5680）；M4 应至少能基于召回材料给出对比，"
        "或明确说材料不足以说明区别——**两种都算合格，硬编答案算不合格**",
        显示命中=0,
    )
    if r3:
        print(f"\n  复核：类型判定 = {r3['类型']} ｜ 召回 {r3['召回条数']} 段 ｜ 是否作答 = {r3['是否作答']}")

    # ---------- 验证④ 出处可追 ----------
    段("验证④ 出处可追：每条出处都要能回原文核对（文件＋标题路径＋行号＋内容指纹）")
    if r1 and r1["出处"]:
        ok = True
        for o in r1["出处"]:
            齐 = bool(o["来源文件"]) and bool(o["标题路径"]) and bool(o["行号"]) and bool(o["内容指纹"])
            ok = ok and 齐
            print(f"    {o['编号']}：文件{'✅' if o['来源文件'] else '❌'} "
                  f"标题{'✅' if o['标题路径'] else '❌'} 行号{'✅' if o['行号'] else '❌'} "
                  f"指纹{'✅' if o['内容指纹'] else '❌'}  → {o['来源文件']} 行 {o['行号']}")
        print(f"\n  出处完整性：{'✅ 四项齐全' if ok else '❌ 有缺项'}")
    else:
        print("  ⚠️ 用例① 未产出出处，无法验证")

    # ---------- 验证⑤ 成本 ----------
    段("验证⑤ 成本：glm-4-flash 属免费档，但 token 仍要能报出")
    总 = 0
    for r in (r1, r2, r3):
        if r and r.get("用量"):
            总 += r["用量"]["total_tokens"]
            print(f"    {r['问题'][:22]:<24} {r['用量']['total_tokens']:>6} tokens ｜ {r['用量']['耗时秒']:>5} 秒")
    print(f"\n  本次合计 {总} tokens ｜ 模型 {G.对话模型}（免费档，费用 0 元）")

    段("M4 试跑完成")
    print("说明：以上每项都在验证一个**具体要求或实测发现**对应的实现，不是泛泛的『跑通』。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
