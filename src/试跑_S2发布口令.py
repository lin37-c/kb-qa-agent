# -*- coding: utf-8 -*-
"""S2 验证：`发布` 的口令闸门能不能真的挡住"模型自发布"。

判据（每条都能证伪）：
  ① `对口令` 只读、且**不返回口令内容**
  ② `生成发布计划` 给出逐文件哈希与"目标是否将被覆盖"，并算出计划指纹
  ③ ★ **无口令 → 拒**；错口令 → 拒
  ④ ★ **一次性**：同一口令用过第二次 → 拒
  ⑤ ★ **绑定计划**：口令只对"那一份计划"有效；换一批文件（指纹变）→ 拒
  ⑥ ★ **四项确认缺项/未过 → 拒**（§6.2③）
  ⑦ 正常路径：真发布 → **逐文件回读哈希与计划一致**
  ⑧ 审计：上面每一次判定都留痕

★ 安全说明：本验证**不碰任何正式交付物** —— 目标选在
`05_项目验证证据\\_发布演练\\`（既定允许直写的运行产物区），演练后清理。
"""
from __future__ import annotations

import importlib.util
import json
import shutil
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:  # noqa: BLE001
    pass

项目根 = Path(r"<workspace>\01_项目\DeepSeek Harness专用\LLM知识库检索与工具调用")
SRC = 项目根 / "02_项目源码与工程" / "src"
候选区 = Path(r"<workspace>\00_资产\04_智能体在用\DeepSeek Harness"
             r"\候选_LLM知识库检索与工具调用_20261013")
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import 护栏    # noqa: E402
import 工具    # noqa: E402

# 发布模块：**人类侧**直接用（模拟"程序这边拿着口令"）
_spec = importlib.util.spec_from_file_location("发布维护", 候选区 / "阶段3_待发布" / "发布维护.py")
发布维护 = importlib.util.module_from_spec(_spec)      # type: ignore[arg-type]
_spec.loader.exec_module(发布维护)                     # type: ignore[union-attr]
assert Path(发布维护.__file__).resolve() == (候选区 / "阶段3_待发布" / "发布维护.py").resolve()

通过: list[str] = []
失败: list[str] = []


def 判(名: str, 过: bool, 详: str = "") -> None:
    (通过 if 过 else 失败).append(名)
    print(f"  {'✅' if 过 else '❌'} {名}" + (f"　—— {详}" if 详 else ""))


def 段(t: str) -> None:
    print("\n" + "=" * 92)
    print(t)
    print("=" * 92)


def 审计行数() -> int:
    f = 项目根 / "04_项目工作过程" / "工具调用轨迹.jsonl"
    return len([l for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]) if f.exists() else 0


def 调(工具名: str, 参数: dict) -> dict:
    try:
        return 工具.调用(工具名, 参数)
    except 护栏.拦截 as e:
        return {"ok": False, "被拦": True, "说明": "；".join(f"[{v['规则']}]{v['判据']}" for v in e.违规)}
    except Exception as e:  # noqa: BLE001
        return {"ok": False, "异常": f"{type(e).__name__}: {e}", "说明": str(e)}


四项 = {"完整无损": True, "对资产包无损失": True, "对agent space无损失": True, "无兼容性冲突": True}


def main() -> int:
    段("S2 验证 · 发布与口令闸门")
    演练根 = 项目根 / "05_项目验证证据" / "_发布演练"
    文件对 = [{"候选相对": "阶段3_待发布/落恢复点维护.py",
             "目标相对": "_发布演练/落恢复点维护.py"},
            {"候选相对": "阶段3_待发布/发布维护.py",
             "目标相对": "_发布演练/发布维护.py"}]
    print(f"候选区  ：{候选区}")
    print(f"演练目标：{演练根}（**属于允许直写的运行产物区**，演练后清理）")
    if 演练根.exists():
        shutil.rmtree(演练根)

    # ---------- ① 对口令（只读，且不返回口令内容） ----------
    段("① 对口令（只读）")
    r = 调("对口令", {})
    print(f"  {r.get('说明')}")
    blob = json.dumps(r, ensure_ascii=False)
    判("① 可用且报告状态", bool(r.get("ok")), str(r.get("数据", {}).get("状态")))
    判("① **不返回口令内容**（回应里没有口令文件里的那个字段值）",
       "口令" not in r.get("数据", {}) or r["数据"].get("口令") is None, "数据里无「口令」键值")

    # ---------- ② 生成发布计划 ----------
    段("② 生成发布计划（只读，把计划摊开给人看）")
    r = 调("生成发布计划", {"文件对": 文件对})
    print(f"  {r.get('说明')}")
    判("② 计划成立", bool(r.get("ok")))
    指纹 = r.get("数据", {}).get("计划指纹", "")
    判("② 有计划指纹", len(指纹) == 16, 指纹)
    判("② 逐文件给出哈希与目标现状",
       all("候选sha256" in x and "目标现状" in x for x in r.get("数据", {}).get("文件", [])),
       f"{len(r.get('数据', {}).get('文件', []))} 个文件")
    r2 = 调("生成发布计划", {"文件对": [{"候选相对": "不存在的文件.py"}]})
    判("② 候选不存在时计划不成立", not r2.get("ok"), r2.get("说明", "")[:60])

    # ---------- ③ 无口令 / 错口令 → 拒 ----------
    段("③ 口令闸门：无口令、错口令")
    #    ★ 判据修正（2026-10-14 自查发现）：第一版**先把口令文件删掉**再测"错口令"，
    #      于是两条都走"还没发行过任何口令"分支 —— **"错口令"根本没被测到**。
    #      现改为：先删（测无口令），再**发行一个真口令**，然后故意填错的去发（测错口令）。
    发布维护.口令文件.unlink(missing_ok=True)      # 清掉历史口令，模拟"还没发行"
    前 = 审计行数()
    r = 发布维护.发布(文件对, 口令="", 四项确认=四项)
    判("③ 无口令 → 拒", not r.get("ok") and "口令" in r.get("说明", ""), r.get("说明", "")[:80])
    发布维护.发行口令(指纹, 备注="S2 验证：错口令测试")
    r = 发布维护.发布(文件对, 口令="DEADBEEF", 四项确认=四项)
    判("③ **错口令 → 拒**（这次真的走到了口令比对分支）",
       not r.get("ok") and "口令不匹配" in r.get("说明", ""), r.get("说明", "")[:80])
    发布维护.口令文件.unlink(missing_ok=True)
    #   ★ 判据修正（2026-10-14 第二次自查）：原断言写"审计 +2"，实测 +3 —— 因为
    #     **`发行口令` 本身也是一次该留痕的动作**（谁在什么时候为什么发行了口令）。
    #     断言改为逐条核对"该留痕的三件事"都留了：拦截、发行、拦截。
    #     **教训同 P-08 第 5 款：计数的口径要写清"算上了哪些动作"**，否则数字对不上时
    #     第一反应会怀疑被测对象，而不是怀疑自己的口径。
    尾部 = [json.loads(l) for l in (项目根 / "04_项目工作过程" / "工具调用轨迹.jsonl")
           .read_text(encoding="utf-8").splitlines() if l.strip()][-(审计行数() - 前):]
    判定序 = [(x.get("工具"), x.get("判定")) for x in 尾部]
    判("③ 三件事都留痕：发布拦截 → 发行口令 → 发布拦截",
       判定序 == [("发布", "拦截"), ("发行口令（人类侧）", "发行"), ("发布", "拦截")],
       f"实际 {判定序}")

    # ---------- ④ 四项确认 ----------
    段("④ 四项确认缺项／未过 → 拒")
    r = 发布维护.发布(文件对, 口令="X", 四项确认={"完整无损": True})
    判("④ 缺项 → 拒", not r.get("ok") and "缺项" in r.get("说明", ""), r.get("说明", "")[:70])
    r = 发布维护.发布(文件对, 口令="X", 四项确认={**四项, "无兼容性冲突": False})
    判("④ 有未过项 → 拒", not r.get("ok") and "未通过" in r.get("说明", ""), r.get("说明", "")[:70])

    # ---------- ⑤ 正常路径：发行口令 → 真发布 → 回读 ----------
    段("⑤ 正常路径：发行口令 → 发布 → 逐文件回读")
    口 = 发布维护.发行口令(指纹, 备注="S2 验证：演练目标")
    print(f"  {口['说明']}")
    判("⑤ 口令已发行且绑定计划指纹", 口.get("ok") and len(口.get("口令", "")) == 8,
       f"口令 {口.get('口令')}（**仅本次验证可见**）")
    r = 发布维护.发布(文件对, 口令=口["口令"], 四项确认=四项, 备注="S2 验证")
    print(f"  {r.get('说明')}")
    判("⑤ 发布成功", bool(r.get("ok")))
    判("⑤ 回读全一致", r.get("数据", {}).get("回读全一致") is True,
       f"{sum(x['回读一致'] for x in r.get('数据', {}).get('明细', []))}/{len(r.get('数据', {}).get('明细', []))}")
    #   ★ 判据修正（2026-10-14 自查发现）：第一版这条写成了
    #     `... == x["计划哈希"] + "" or True` —— **末尾那个 `or True` 让断言恒真**，
    #     等于**没检查**。这正是 R-7.3 第 3 项（可迁移的判断标准）与 P-08 第 4 款
    #     （优先做能证伪的判据）要防的东西：**假断言比没断言更坏，因为它看起来通过**。
    #     现改为：与候选文件**现算哈希**逐条比对。
    明细 = r.get("数据", {}).get("明细", [])
    对照 = []
    for x in 明细:
        tp = Path(x["目标路径"])
        cp = 候选区 / "阶段3_待发布" / Path(x["候选相对"]).name
        对照.append((x["目标路径"], tp.exists() and cp.exists()
                   and 发布维护.文件sha256(tp) == 发布维护.文件sha256(cp)))
    判("⑤ 目标文件落盘且哈希与**候选现算**一致",
       bool(对照) and all(ok for _, ok in 对照),
       f"{sum(1 for _, ok in 对照 if ok)}/{len(对照)} 一致")

    # ---------- ⑥ 一次性：同一口令再用 → 拒 ----------
    段("⑥ 一次性：同一口令用第二次")
    r = 发布维护.发布(文件对, 口令=口["口令"], 四项确认=四项)
    判("⑥ 复用同一口令 → 拒（一次性）",
       not r.get("ok") and ("已被使用" in r.get("说明", "") or "过期" in r.get("说明", "")),
       r.get("说明", "")[:80])

    # ---------- ⑦ 绑定计划：换一批文件 → 旧口令无效 ----------
    段("⑦ 绑定计划：换一批文件（指纹变）后旧口令失效")
    口2 = 发布维护.发行口令(指纹, 备注="S2 验证：绑定测试")
    另一批 = [{"候选相对": "阶段3_待发布/落恢复点维护.py", "目标相对": "_发布演练/另建一名.py"}]
    r = 发布维护.发布(另一批, 口令=口2["口令"], 四项确认=四项)
    判("⑦ 拿 A 计划的口令去发 B 计划 → 拒",
       not r.get("ok") and "绑定的不是这份计划" in r.get("说明", ""), r.get("说明", "")[:90])

    # ---------- ⑧ 篡改候选内容 → 口令失效 ----------
    段("⑧ 发布前候选内容被改动 → 计划指纹变 → 旧口令失效")
    口3 = 发布维护.发行口令(指纹, 备注="S2 验证：篡改测试")
    cp = 候选区 / "阶段3_待发布" / "落恢复点维护.py"
    原文 = cp.read_bytes()
    cp.write_bytes(原文 + b"\n# tamper\n")
    r = 发布维护.发布(文件对, 口令=口3["口令"], 四项确认=四项)
    判("⑧ 候选被改后旧口令失效（指纹不符）",
       not r.get("ok") and ("绑定的不是这份计划" in r.get("说明", "")), r.get("说明", "")[:90])
    cp.write_bytes(原文)

    # ---------- 清理 ----------
    段("清理演练产物")
    if 演练根.exists():
        shutil.rmtree(演练根)
    发布维护.口令文件.unlink(missing_ok=True)
    判("⑧ 演练目录已清理（不污染证据区）", not 演练根.exists(), str(演练根))
    判("⑧ 口令文件已清理", not 发布维护.口令文件.exists(), str(发布维护.口令文件))

    段("汇总")
    print(f"通过 {len(通过)} 项　｜　失败 {len(失败)} 项")
    for x in 失败:
        print(f"  ❌ {x}")
    print(f"\n审计日志当前行数：{审计行数()}")
    return 1 if 失败 else 0


if __name__ == "__main__":
    sys.exit(main())
