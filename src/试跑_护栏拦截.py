    写前 = time.time()
    # ★ 2026-10-25 修：原来写死文件名，第一次跑成功后**再跑必被 P-12 拦住**
    #   （目标已存在 且 无恢复点副本 且 未声明 allow_overwrite）——那是护栏在正常工作，
