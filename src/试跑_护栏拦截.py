def 判(名: str, 过: bool, 详: str = "") -> None:
    (通过 if 过 else 失败).append(名)
    print(f"  {'✅' if 过 else '❌'} {名}" + (f"　—— {详}" if 详 else ""))


def 段(t: str) -> None:
    print("\n" + "=" * 94)
    print(t)
    print("=" * 94)


def 审计行数() -> int:
    if not 护栏.审计日志.exists():
        return 0
    return len([l for l in 护栏.审计日志.read_text(encoding="utf-8").splitlines() if l.strip()])


def 探针(名: str, 工具名: str, 参数: dict, 期望: str, 声明: dict | None = None) -> dict:
    """跑一条探针。期望取值：'拒' 或 '放行'。"""
    前 = 审计行数()
    try:
        工具.调用(工具名, 参数, 声明)
        实际, 违规 = "放行", []
    except 护栏.拦截 as e:
        实际, 违规 = "拒", e.违规
    后 = 审计行数()
    print(f"\n【{名}】")
    print(f"  调用：{工具名}({json.dumps(参数, ensure_ascii=False)[:150]})")
    print(f"  实际：{实际}" + (f"　触发规则 {[v['规则'] for v in 违规]}" if 违规 else ""))
    for v in 违规:
        print(f"        · [{v['规则']}] {v['判据']}")
        if v.get("证据"):
            print(f"          证据：{v['证据'][:90]}")
        if v.get("修法"):
            print(f"          修法：{v['修法'][:100]}")
    判(f"{名}｜判定符合期望（{期望}）", 实际 == 期望, f"实际 {实际}")
    判(f"{名}｜判定已进审计日志", 后 - 前 == 1, f"审计 +{后 - 前}")
    return {"探针": 名, "期望": 期望, "实际": 实际, "违规": 违规}


def 目录哈希(根: Path, 后缀: tuple[str, ...] = (".py", ".md")) -> dict[str, str]:
    出 = {}
    for p in sorted(根.rglob("*")):
        if p.is_file() and (not 后缀 or p.suffix in 后缀):
            h = hashlib.sha256()
            with p.open("rb") as f:
                for 块 in iter(lambda: f.read(1 << 20), b""):
                    h.update(块)
            出[p.relative_to(根).as_posix()] = h.hexdigest()
    return 出


def main() -> int:
    段("M6 阶段 2 · 护栏拦截探针（先探针，后真写）")
    print(f"候选区：{护栏.候选区根}")
    print(f"审计起点：{审计行数()} 行")

    # ---------- 前置：造一个"已存在但无恢复点"的目标，供探针①用 ----------
