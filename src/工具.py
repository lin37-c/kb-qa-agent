# 工具 5：列未决（R-6 单一登记处）
# ===========================================================================
_状态记号 = ("`等触发`", "`等决定`", "`已到点`", "`处理中`", "`已解决`", "`已转出`", "`已作废`")


def _列未决(状态: str = "未解决") -> dict:
    if not 未决表.exists():
        return {"ok": False, "工具": "列未决", "说明": f"未决表不存在：{未决表}",
                "证据": [], "数据": {}}
    文 = 未决表.read_text(encoding="utf-8")
    条 = []
    # 表格行：| **U-NN** ... | 触发条件 | ... | `状态` |
    # ★ 口径修正（2026-10-14 第一版写错）：原正则要求编号**必须**有 `**加粗**`，
    #   于是漏掉了表格里没加粗的那几条 —— 表现为"解析出 26 条"，看着正常，
    #   但比实际少。**少几条比报错更难发现**（P-08 第 5 款：口径要写明）。
    #   现改为加粗可选，并对每个编号**只取第一次出现**（同号在"已解决"区会重复出现）。
    for m in re.finditer(r"^\|\s*(?:\*\*)?(U-\d+)(?:\*\*)?\s*\|(.+)$", 文, re.M):
        编号, 其余 = m.group(1), m.group(2)
        if any(x["编号"] == 编号 for x in 条):
            continue
        单元 = [c.strip() for c in 其余.split("|")]
        状态值 = next((s.strip("`") for s in 单元 if s.strip() in _状态记号), "")
        # ★ 长度口径（2026-10-14 实测修正）：第一版把「事项」截到 120 字，
        #   结果第 3 条的尾部「（源自 2026-10-14 漏项，U-34 条）」被截掉 ——
        #   **标识符被截断后，模型就无法引用它**（实测：模型答的三条里只有一条带得出编号）。
        #   这是"我给的数据不全，却怪模型答得不全"。放宽到 240 字，保留标识符。
        条.append({
            "编号": 编号,
            "事项": 单元[0][:240] if 单元 else "",
            "在等什么": next((c for c in 单元 if ("等" in c and len(c) > 4)), "")[:200],
            "状态": 状态值 or "未标注",
        })
    if 状态 == "未解决":
        显示 = [x for x in 条 if x["状态"] not in ("已解决", "已作废")]
    elif 状态 == "全部":
        显示 = 条
    else:
        显示 = [x for x in 条 if x["状态"] == 状态]
    return {
        "ok": True, "工具": "列未决",
        "数据": {"表": str(未决表), "解析条目总数": len(条), "筛选": 状态, "条目": 显示},
        "证据": [{"来源文件": str(未决表), "内容指纹": _sha256文件(未决表)[:16]}],
        "说明": f"共解析 {len(条)} 条，筛选「{状态}」后 {len(显示)} 条",
        "费用": {"embedding": "0", "生成": "0"},
    }


