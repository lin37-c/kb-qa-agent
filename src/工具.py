def _读路径安全(路径: str) -> tuple[Path | None, str]:
    p = Path(路径)
    if not p.is_absolute():
        p = 项目根 / p
    try:
        ap = p.resolve()
    except OSError:
        return None, f"路径无法解析：{路径}"
    归 = 护栏.路径归属(ap)
    if 归["类别"] == "区外":
        return None, f"拒绝读取：{ap} 不在可读范围内（项目／资产包／候选区）"
    if not ap.exists():
        return None, f"路径不存在：{ap}"
    if ap.is_dir():
        return None, f"这是目录不是文件：{ap}"
    return ap, ""


def _目录路径安全(路径: str) -> tuple[Path | None, str]:
    """与 `_读路径安全` **同一套口径**，只多一条：允许目录。

    ★ 为什么不复用 `_读路径安全`：它有一条"这是目录不是文件"的拒绝 ——
      对读文件是对的，对列目录正好相反。
    ★ 但两者**必须共用同一套归属判据**（`护栏.路径归属`）——
      否则又是"同一件事两处写法"（F-40 同族：改一处、别处不同步）。
    """
    p = Path(路径) if 路径 else 项目根
    if not p.is_absolute():
        p = 项目根 / p
    try:
        ap = p.resolve()
    except OSError:
        return None, f"路径无法解析：{路径}"
    归 = 护栏.路径归属(ap)
    if 归["类别"] == "区外":
        return None, f"拒绝列出：{ap} 不在可读范围内（项目／资产包／候选区）"
    if not ap.exists():
        return None, f"路径不存在：{ap}"
    if not ap.is_dir():
        return None, f"这是文件不是目录（要读内容请用 `读文件`）：{ap}"
    return ap, ""


def _列目录(路径: str = "", 递归: bool = False, 含隐藏: bool = False,
          最多: int = 200) -> dict:
    """列出**授权区域内**某目录下的条目（只读）。

    ★ 为什么要这个工具（S4 实测，F-42）：
        问「护栏登记了几个检查项」时，模型**只能猜文件名**（它猜了 `工具调用护栏.py`），
        猜不中就再也找不到 —— 因为工具集里**没有任何"发现文件"的手段**。
        ★ 关键是：**模型当时的行为是对的**（猜不中就如实说"没有"，没编造），
          错的是**我们没给它发现的手段**。本工具就是补这一环。
    返回：每个条目的 名称／类型／字节数／相对路径（★ **不返回内容**，只给元信息）。
    """
    忽略 = {"__pycache__", ".venv", ".git", "node_modules", ".pytest_cache"}
    ap, 错 = _目录路径安全(路径)
    if ap is None:
        return {"ok": False, "工具": "列目录", "说明": 错, "证据": [], "数据": {}}
    条目, 被略 = [], 0
    it = ap.rglob("*") if 递归 else ap.iterdir()
    for x in sorted(it, key=lambda y: (y.is_dir(), y.name)):
        if x.name in 忽略 or (not 含隐藏 and x.name.startswith(".")):
            被略 += 1
            continue
        try:
            条 = {"名称": x.name, "类型": "目录" if x.is_dir() else "文件",
                 "字节": 0 if x.is_dir() else x.stat().st_size,
                 "相对路径": str(x.relative_to(ap))}
        except OSError:
            continue
        条目.append(条)
        if len(条目) >= 最多:
            break
    return {
        "ok": True, "工具": "列目录",
        "数据": {"目录": str(ap), "条目": 条目, "条数": len(条目),
                "递归": 递归, "被略过": 被略, "是否截断": len(条目) >= 最多},
        "说明": (f"列出 {ap}（{'递归' if 递归 else '仅本层'}）：**{len(条目)} 个条目**"
                + (f"，已截断到 {最多}" if len(条目) >= 最多 else "")
                + (f"，略过隐藏/缓存 {被略} 个" if 被略 else "")),
        "证据": [{"目录": str(ap), "条数": len(条目)}],
        "费用": {"embedding": "0", "生成": "0"},
    }


