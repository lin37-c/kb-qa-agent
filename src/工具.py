_现行禁令缓存: dict = {"编号": None, "定义文件": None}


def _现行禁令编号() -> tuple[list[str], str]:
    """从语料**现算**现行禁令编号集合（不硬编码，避免与资产包脱同步）。

    为什么需要它（2026-10-14 实测教训，本任务最严重的一次幻觉）：
        模型调 `查规则条文({"编号": "P-1"})`（P-1 不是现行编号，现行是 P-01~P-14），
        工具如实回了"未找到定义"，但因为**返回里没有任何"它不存在"的强信号**，
        模型就把返回文本里出现的 P-12 当成补充说明，最终答出
        「**这条禁令的编号是 P-1**」——**编号是编造的**。
        修法：查不到时**明确说"该编号不在现行禁令清单内"**，并把**真实清单列出来**
        给它选。这与 M4 生成层"资料里没有就说没有"是同一条要求（R-1／P-07）落在工具层。
    """
    if _现行禁令缓存["编号"] is not None:
        return _现行禁令缓存["编号"], _现行禁令缓存["定义文件"]
    定义文件 = 资产包根 / "04_来源版本与校验" / "03_维护与改进" / "分歧与改进记录.md"
    编号: list[str] = []
    if 定义文件.exists():
        文 = 定义文件.read_text(encoding="utf-8")
        编号 = sorted(set(re.findall(r"^#{2,4}\s*【禁令】(P-\d{1,2})", 文, re.M)))
    _现行禁令缓存["编号"] = 编号
    _现行禁令缓存["定义文件"] = str(定义文件)
    return 编号, str(定义文件)


