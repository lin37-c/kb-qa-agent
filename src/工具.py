def 表单() -> list[dict]:
    """给模型看的工具清单（OpenAI 兼容格式）。"""
    return [{
        "type": "function",
        "function": {"name": n, "description": t["描述"], "parameters": t["参数"]},
    } for n, t in TOOLS.items()]


def _校验参数(工具名: str, 参数: dict) -> tuple[dict, list[str]]:
    """schema 校验。返回（规范化后的参数, 错误列表）。未知参数直接拒。"""
    模式 = TOOLS[工具名]["参数"]
    错 = []
    属性 = 模式["properties"]
    未知 = set(参数) - set(属性)
    if 未知:
        错.append(f"未知参数：{'、'.join(sorted(未知))}（本工具只接受 {'、'.join(属性)}）")
    缺 = [k for k in 模式["required"] if k not in 参数 or 参数[k] in ("", None)]
    if 缺:
        错.append(f"缺必填参数：{'、'.join(缺)}")
    规范 = {}
    for k, v in 参数.items():
        if k not in 属性:
            continue
        期望 = 属性[k]["type"]
        if 期望 == "integer":
            try:
                v = int(v)
            except (TypeError, ValueError):
                错.append(f"参数 {k} 应为整数，收到 {v!r}")
                continue
        elif 期望 == "string" and not isinstance(v, str):
            错.append(f"参数 {k} 应为字符串，收到 {type(v).__name__}")
            continue
        规范[k] = v
    return 规范, 错


def 调用(工具名: str, 参数: dict, 声明: dict | None = None) -> dict:
    """工具调用的唯一入口：**先过护栏，再执行**。

    `声明` 是"调用方对本次操作的显式表态"，例如 {"allow_overwrite": True}。
    它**不放进工具的 schema**：schema 是给模型看的，而"是否授权覆盖"必须由
    调用方（人／上层流程）表态，不能让模型自己填 True 把护栏绕过去。
    """
    if 工具名 not in TOOLS:
        记录 = 护栏.检查操作(工具名, 参数 or {}, 声明)   # 会抛（未登记 → 白名单拦截）
        return {"ok": False, "工具": 工具名, "说明": "未登记的工具", "数据": {}, "证据": []}

    规范, 错 = _校验参数(工具名, 参数 or {})
    if 错:
        # 参数错也要留审计（P-08：参数错就是口径错，必须可见）
        护栏.落审计({"时间": __import__("datetime").datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                  "工具": 工具名, "参数摘要": 护栏._参数摘要(参数 or {}),
                  "检查项": ["参数合法"], "判定": "拦截",
                  "违规": [{"规则": "P-08", "判据": e, "证据": ""} for e in 错]})
        return {"ok": False, "工具": 工具名, "说明": "参数不合法：" + "；".join(错),
                "数据": {}, "证据": [], "未执行": True}

    # 写类工具：**路径解析由护栏统一做**（解析失败也会留审计）。
    # 这里不再自己解析 —— 避免"护栏之外先抛"导致拦截无痕，也避免两处口径漂移。
    记录 = 护栏.检查操作(工具名, 规范, 声明)
    解析后 = 记录.get("解析后路径")
    # ★ 只给"**确实声明了 `路径` 参数**的工具注入解析结果（2026-10-14 实测踩到）：
    #   `落恢复点` 走的是「目标根 ＋ 范围」形式、签名里没有 `路径`，
    #   无条件注入会让它报 `unexpected keyword argument '路径'`。
    #   **护栏为它设的"解析后路径"是落点信息，不是要回传给它的参数** —— 两者别混。
    if 解析后 and "路径" in TOOLS[工具名]["参数"].get("properties", {}):
        规范 = dict(规范)
        规范["路径"] = 解析后
    return TOOLS[工具名]["实现"](**规范)


