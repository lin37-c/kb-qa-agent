def _查项目状态(项: str = "全部") -> dict:
    数据: dict = {}
    证据: list = []
    if 项 in ("全部", "索引"):
        # ★ 复用产品自身的加载函数（`入库.载入向量库`），不自己拼文件路径。
        #   第一版这里写错了口径：去读 `data\向量库\索引.json` —— 那个文件不存在，
        #   `索引.json` 是**缓存**目录下的东西（指纹→位置），不是向量库的。
        #   教训与 F-13 同型：**自己另写一条读取路径，读到的就不是产品在读的东西**。
        import 入库 as K
        元数据路径 = K.元数据路径
        向量路径 = K.向量路径
        if 元数据路径.exists():
            行 = [l for l in 元数据路径.read_text(encoding="utf-8").splitlines() if l.strip()]
            字符数 = 0
            for l in 行:
                try:
                    字符数 += int(json.loads(l).get("字符数", 0) or 0)
                except Exception:  # noqa: BLE001
                    pass
            数据["索引"] = {
                "元数据文件": str(元数据路径), "块数": len(行), "总字符数": 字符数,
                "元数据字节": 元数据路径.stat().st_size,
                "向量文件字节": 向量路径.stat().st_size if 向量路径.exists() else 0,
            }
            证据.append({"来源文件": str(元数据路径), "内容指纹": _sha256文件(元数据路径)[:16]})
        else:
            数据["索引"] = {"元数据文件": str(元数据路径), "状态": "不存在"}
    if 项 in ("全部", "账本"):
        if 账本.exists():
            行 = [l for l in 账本.read_text(encoding="utf-8").splitlines() if l.strip()]
            总费 = 0.0
            tokens = 0
            坏行 = 0
            for l in 行:
                try:
                    j = json.loads(l)
                    # ★ 字段名是 `费用_元`（见 向量化._记用量）。第一版我写成 `费用`，
                    #   于是"账本可读但累计 0 元"——**读数错比读不到更危险**（P-08 第 5 款）。
                    总费 += float(j.get("费用_元", 0) or 0)
                    tokens += int(j.get("tokens", 0) or 0)
                except Exception:  # noqa: BLE001
                    坏行 += 1
            数据["账本"] = {"文件": str(账本), "条数": len(行), "累计费用": round(总费, 8),
                          "累计tokens": tokens, "无法解析行": 坏行,
                          "字段口径": "费用_元／tokens（与 向量化._记用量 一致）"}
            证据.append({"来源文件": str(账本), "条数": len(行)})
        else:
            数据["账本"] = {"文件": str(账本), "状态": "不存在"}
    if 项 in ("全部", "恢复点"):
        rs = sorted(护栏.恢复点根.glob("LLM知识库检索与工具调用_*"))
        数据["恢复点"] = {
            "目录": str(护栏.恢复点根),
            "本项目份数": len(rs),
            "最近三份": [x.name for x in rs[-3:]],
        }
