# 工具 2：查规则条文（F-2「编号定义与调用分离」的正解）
# ===========================================================================
def _查规则条文(编号: str) -> dict:
    编号 = 编号.strip().upper()
    if not re.fullmatch(r"P-\d{1,2}", 编号):
        return {"ok": False, "工具": "查规则条文",
                "说明": f"编号格式应为 P-数字（如 P-12），收到：{编号}",
                "证据": [], "数据": {}}
    现行, 定义文件 = _现行禁令编号()
    # 编号写法归一：P-1 与 P-01 指同一条（资产包正式写法是补零的 P-01）
    归一幅本 = {x.lstrip("P-").lstrip("0") or "0": x for x in 现行}
    正式编号 = 归一幅本.get(编号[2:].lstrip("0") or "0")

    if 正式编号 is None:
        # ★ 明确说"不存在"，并给出真实清单 —— 不给模型留下猜的空间
        return {
            "ok": True, "工具": "查规则条文",
            "数据": {"编号": 编号, "存在": False, "现行禁令": 现行, "定义文件": 定义文件},
            "证据": [{"来源文件": 定义文件, "说明": "现行禁令定义所在文件"}],
            "说明": f"★ 禁令 {编号} **不在现行禁令清单内**（现行共 {len(现行)} 条："
                    f"{'、'.join(现行)}）。不得把其他编号的条文当作 {编号} 的内容回答。",
            "费用": {"embedding": "0（未检索）", "生成": "0"},
        }

    # 用产品检索函数查，不自己造一条检索路径（F-13）
    r = _查知识库(f"禁令 {正式编号} 说的是什么", 取前=5, 分组="维护")
    命中 = r["数据"]["命中"]
    定义 = [h for h in 命中 if "禁令" in (h["标题路径"] or "") and 正式编号 in (h["标题路径"] or "")]
    return {
        "ok": True, "工具": "查规则条文",
        "数据": {
            "编号": 正式编号,
            "请求的编号": 编号,
            "存在": True,
            "定义条文": 定义,
            "是否找到定义": bool(定义),
            "最高相似度": r["数据"]["最高相似度"],
            "其他候选": [h for h in 命中 if h not in 定义],
            "现行禁令": 现行,
        },
        "证据": r["证据"],
        "说明": (f"{正式编号} 的定义条文已定位（{len(定义)} 段）" if 定义
                else f"{正式编号} 在现行清单内，但本次检索没认出它的定义段"
                     f"（如实报未找到，不编造条文）"),
        "费用": r["费用"],
    }


# ===========================================================================
# 工具 3：读文件（带内容指纹，供后续哈希比对与 P-08 回读）
# ===========================================================================
def _读文件(路径: str, 起行: int = 1, 止行: int = 0, 最大字符: int = 4000) -> dict:
    ap, 错 = _读路径安全(路径)
    if ap is None:
        return {"ok": False, "工具": "读文件", "说明": 错, "证据": [], "数据": {}}
    try:
        全 = ap.read_text(encoding="utf-8")
        编码 = "utf-8"
    except UnicodeDecodeError:
        全 = ap.read_text(encoding="utf-8", errors="replace")
        编码 = "utf-8(replace)"
    行 = 全.splitlines()
    起 = max(1, int(起行))
    止 = len(行) if not 止行 or int(止行) <= 0 else min(int(止行), len(行))
    片 = "\n".join(行[起 - 1:止])
    截断 = len(片) > 最大字符
    if 截断:
        片 = 片[:最大字符]
    指纹 = _sha256文件(ap)
    return {
        "ok": True, "工具": "读文件",
        "数据": {
            "路径": str(ap), "总行数": len(行), "取行": f"{起}–{止}",
            "字符数": len(全), "字节": ap.stat().st_size, "编码": 编码,
            "sha256": 指纹, "是否截断": 截断, "内容": 片,
        },
        "证据": [{"来源文件": str(ap), "行号": f"{起}–{止}", "sha256": 指纹}],
        "说明": f"{ap.name} 第 {起}–{止} 行（共 {len(行)} 行，{ap.stat().st_size:,} B）"
                + ("——已截断" if 截断 else ""),
        "费用": {"embedding": "0（不调接口）", "生成": "0"},
    }


