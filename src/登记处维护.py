def 追加账本(场景: str, tokens: int, 模型: str = "embedding-3",
           单价_元每百万token: float = 0.5) -> dict:
    """往账本**追加**一行（字段与 `向量化._记用量` 完全一致：时间／场景／模型／tokens／费用_元）。

    ★ 为什么费用由本函数**按 tokens 算**而不是让人填：账本的价值在于**口径统一**。
      若允许外部直接填一个金额，迟早会出现"两个地方算法不同"（F-14 那类估算偏差就是口径不统一）。
    """
    if not isinstance(tokens, int) or tokens < 0:
        return {"ok": False, "说明": f"tokens 必须是非负整数，收到 {tokens!r}", "数据": {}, "证据": []}
    费用 = round(tokens / 1_000_000 * 单价_元每百万token, 8)
    行 = {"时间": datetime.now().strftime("%Y-%m-%d %H:%M:%S"), "场景": 场景,
          "模型": 模型, "tokens": tokens, "费用_元": 费用}
    前 = 账本.read_text(encoding="utf-8") if 账本.exists() else ""
    前条数 = len([l for l in 前.splitlines() if l.strip()])
    账本.parent.mkdir(parents=True, exist_ok=True)
    with 账本.open("a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(行, ensure_ascii=False) + "\n")
    # 回读：条数 +1，且**最后一行就是这一条**
    尾 = [l for l in 账本.read_text(encoding="utf-8").splitlines() if l.strip()]
    检查 = {"条数 +1": len(尾) == 前条数 + 1,
           "最后一行就是本次追加": json.loads(尾[-1]) == 行,
           "原有行未被改动": "\n".join(尾[:-1]) == 前.rstrip("\n").lstrip("\ufeff") if 前 else True}
    if not all(检查.values()):
        return {"ok": False, "说明": f"回读核对未通过：{检查}", "数据": {"检查": 检查}, "证据": []}
    return {"ok": True, "工具": "追加账本",
            "数据": {"文件": str(账本), "追加行": 行, "条数": len(尾), "回读检查": 检查},
            "证据": [{"文件": str(账本), "条数": len(尾), "本次费用": 费用}],
            "说明": f"已追加账本 1 行（场景 {场景}，{tokens} tokens，{费用} 元），现共 {len(尾)} 条",
            "费用": {"embedding": "0", "生成": "0"}}


