def 文件sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for 块 in iter(lambda: f.read(1 << 20), b""):
            h.update(块)
    return h.hexdigest()


def _取下一个编号(文: str, 前缀: str, 模式: str) -> str:
    """扫全文取该前缀的最大编号，返回下一个。

    ★ 两个坑（2026-10-14 自测当场抓到，如实留痕）：
      ① 第一版直接 `int(m)` —— 而正则会连前缀一起捕获（`F-7`），于是 `int('F-7')` 报错。
         现统一只取数字部分。
      ② 第一版的 R 编号正则写成 `^## [^#\\n]*要求 (R-\\d+)`，**没匹配到任何一条**，
         于是"下一个"算成了 `R-1` —— 而文档里已有 `R-7`／`R-7.1`／`R-7.2`／`R-7.3`。
         **取号错了会导致重号**（两条要求同号），所以这里必须扫得到。
         现改为直接扫 `R-<数字>` / `R-<数字>.<数字>`（含小节标题里的 R-7.1 这类）。
      ③ 含小数点的编号（R-7.3）**不参与"下一个整数号"的计算**，但它们的存在要使
         下一个整数号 > 其整数部分 —— 否则会生成 R-7 与既有 R-7.x 混淆。
    """
    粗 = [m for m in re.findall(rf"{前缀}-(\d+(?:\.\d+)?)", 文)]
    整数 = [int(x) for x in 粗 if "." not in x]
    小数 = [float(x) for x in 粗 if "." in x]
    下 = (max(整数) + 1) if 整数 else 1
    # ★ 若最大的整数号**已经有小数子款**（如 R-7 下面有 R-7.1/R-7.2/R-7.3），
    #   那么下一条应接成 **R-7.4**，而不是跳到 R-8 ——
    #   否则会在 R-7 与 R-8 之间留下一串空的小数位，读的人会以为是漏号。
    if 小数 and int(max(小数)) == max(整数 or [0]) and max(小数) >= max(整数 or [0]):
        次 = int(round((max(小数) - int(max(小数))) * 10)) + 1
        return f"{前缀}-{int(max(小数))}.{次}"
    宽 = 2 if any(len(str(x)) >= 2 for x in 整数) or 下 >= 10 else 1
    return f"{前缀}-{下:0{宽}d}"


def _插入(路径: Path, 锚点: str, 新段: str) -> dict:
    """在锚点**之前**插入新段，然后回读核对（只多不少、原内容逐字节保留）。

    ★ BOM 纪律（2026-10-14 实测教训）：读写必须**保留原文件的 BOM 状态** ——
      原文件若带 UTF-8 BOM，就先剥掉再比、写回时**按原状态加回**。
      否则会在"首行"引入一个**不可见的差异**：两份文件看起来一样、比出来不相等，
      段落级核对会报"首行被丢"（假失败），追查半天只是一个 `\\ufeff`。
    """
    raw = 路径.read_bytes()
    有BOM = raw[:3] == b"\xef\xbb\xbf"
    前文 = raw.decode("utf-8-sig")
    前哈希, 前字节 = 文件sha256(路径), len(raw)
    if 锚点 not in 前文:
        return {"ok": False, "说明": f"锚点不存在，不敢盲插：{锚点}", "数据": {}, "证据": []}
    位置 = 前文.index(锚点)
    后文 = 前文[:位置] + 新段 + 前文[位置:]
    路径.write_bytes(("\ufeff" if 有BOM else "").encode("utf-8") + 后文.encode("utf-8"))

    # ★ 回读核对（两道，缺一不算成功）
    #   ★ 读回**也要剥 BOM**（`utf-8-sig`）—— 加 BOM 纪律时第一版漏了这一步：
    #     写回时带了 BOM、读回时没剥，于是"原有内容未被删改"必然为假 → **假失败**。
    #     判据：**同一份内容，读和写的口径必须一致**（这是 F-36 那类"取值口径"错误的又一实例）。
    回 = 路径.read_bytes().decode("utf-8-sig")
    后哈希, 后字节 = 文件sha256(路径), len(回.encode("utf-8"))
    增字节 = len(新段.encode("utf-8"))
    检查 = {
        "新段已写入": 新段.strip()[:40] in 回,
        "原有内容未被删改": 回.replace(新段, "", 1) == 前文,
        "字节增量＝新段字节": 后字节 - 前字节 == 增字节,
    }
    if not all(检查.values()):
        return {"ok": False, "说明": f"回读核对未通过：{检查}",
                "数据": {"前哈希": 前哈希[:16], "后哈希": 后哈希[:16],
                        "前字节": 前字节, "后字节": 后字节, "检查": 检查}, "证据": []}
    return {"ok": True, "说明": "写入并回读通过",
            "数据": {"文件": str(路径), "前字节": 前字节, "后字节": 后字节,
                    "新增字节": 增字节, "前sha256": 前哈希, "后sha256": 后哈希,
                    "回读检查": 检查},
            "证据": [{"文件": str(路径), "后sha256": 后哈希[:16], "新增字节": 增字节}]}


