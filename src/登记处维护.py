def 记要求(正文: str, 标题: str = "", 原话: str = "") -> dict:
    """在需求文档追加一条要求：`## 十·补N、要求 R-N：标题`。"""
    文 = 需求文档.read_text(encoding="utf-8")
    号 = _取下一个编号(文, "R", r"^## [^#\n]*要求 (R-\d+)")
    既有十补 = re.findall(r"^## 十·补(\d*)", 文, re.M)
    次 = (max((int(x) for x in 既有十补 if x.isdigit()), default=0) + 1)
    节标题 = f"## 十·补{次}、要求 {号}：{标题 or '（待补标题）'}（{datetime.now():%Y-%m-%d} 用户新增）\n\n"
    内容 = [节标题]
    if 原话:
        内容.append("> **用户原话（原文留档，不转述）**\n>\n> > " + 原话.strip().replace("\n", "\n> > ") + "\n\n")
    内容.append(正文.strip() + "\n\n---\n\n")
    新段 = "".join(内容)
    锚 = "## 九、本次落盘说明（如实登记）"
    r = _插入(需求文档, 锚, 新段)
    r["数据"]["编号"] = 号
    r["说明"] = f"已登记要求 {号}（{r['说明']}）"
    return r


def 记素材(标题: str, 问题机制: str, 怎么发现: str, 数据证据: str, 怎么讲: str,
          岗位方向: str, 可承接追问: str = "", 前缀: str = "T") -> dict:
    """在素材库追加一条素材：`# N·补二、T-N ★ 标题` ＋ 四要素表。"""
    if 岗位方向.split("（")[0].strip() not in 岗位方向取值 and "（主" not in 岗位方向:
        return {"ok": False, "说明": f"岗位方向取值必须是 {'／'.join(岗位方向取值)} 之一"
                                f"（可带「（主…」标注），收到：{岗位方向}", "数据": {}, "证据": []}
    文 = 素材库.read_text(encoding="utf-8")
    号 = _取下一个编号(文, 前缀, rf"^#+ *[^\n]*?({前缀}-\d+)")
    缺 = [k for k, v in {"问题机制": 问题机制, "怎么发现": 怎么发现,
                        "数据证据": 数据证据, "怎么讲": 怎么讲}.items() if not v.strip()]
    if 缺:
        return {"ok": False, "说明": f"四要素缺项，不许登记：{缺}", "数据": {}, "证据": []}
    新段 = (
        f"## {号} ★ {标题}\n\n"
        f"| | |\n|---|---|\n"
        f"| **问题／机制** | {问题机制.strip()} |\n"
        f"| **怎么发现的** | {怎么发现.strip()} |\n"
        f"| **数据／证据** | {数据证据.strip()} |\n"
        f"| **怎么讲** | {怎么讲.strip()} |\n"
        f"| **岗位方向** ★ | {岗位方向.strip()} |\n"
        f"| **可承接的追问** | {可承接追问.strip() or '（待补）'} |\n\n---\n\n"
    )
    r = _插入(素材库, 素材库锚点, 新段)
    r["数据"]["编号"] = 号
    r["说明"] = f"已登记素材 {号}（{r['说明']}）"
    return r


def _该行属于哪一节(文: str, 编号: str) -> str | None:
    """在**已写入的全文**里，找出 `编号` 这一行落在哪个 `## 乙-x` 小节内。找不到返回 None。

    ★ 为什么需要它（2026-10-14 实证，F-41）：
        `记成果()` 原来只核"新行在不在文件里" —— **不核"落在哪一节"**。
        于是当锚点算错、或调用时 `类别` 与锚点不一致时，**它会把条目追加进错误的小节，
        却依然返回"写入并回读通过"**。实测后果：10 条成果被一律塞进乙-3。
        **"写入成功"≠"写对了地方"** —— 位置必须**独立核对**。
    """
    现 = None
    for l in 文.splitlines():
        if l.startswith("## 乙-1"):
            现 = "乙-1"
        elif l.startswith("## 乙-2"):
            现 = "乙-2"
        elif l.startswith("## 乙-3"):
            现 = "乙-3"
        #   ★★ 补 乙-4（2026-10-15 实测修复）：漏了它 ⇒ 乙-4 段内被读成"仍是乙-3"，
        #     于是"类别=乙-3 却被写进乙-4"这种错位**骗过了核对**（F-41 复发形态）。
        elif l.startswith("## 乙-4"):
            现 = "乙-4"
        elif l.startswith(("# 一句话总结", "## 变更记录", "# 甲类", "# 乙类")):
            现 = None                     # 出了乙类区
        m = re.match(rf"^\|\s*\*\*{re.escape(编号)}\*\*", l)
        if m:
            return 现
    return None


def _找小节起点(文: str, 标题: str) -> int:
    """找**行首**出现的 `标题`，返回其字符位置；找不到返回 -1。

    ★ 为什么不能直接用 `文.index(标题)`（2026-10-14 实证，又一次同族错误）：
        实测 `文.index("## 乙-3")` 匹配到了**正文里提到的那个字符串**
        （S4 的成果条目里就写着 `## 乙-3`），于是插点算到了**上一节（乙-1）段尾** ——
        **新条目会被追加进错误的小节**。
        这与 F-41 同族：**"看起来像目标"不等于"就是目标"**。
        判据必须收紧到"**该行以这个标题开头**"。
    """
    for i, l in enumerate(文.splitlines(keepends=True)):
        if l.startswith(标题):
            return sum(len(x) for x in 文.splitlines(keepends=True)[:i])
    return -1


def 记成果(标题: str, 性质: str, 怎么发现: str, 证据: str, 处置: str,
          类别: str = "乙-2") -> dict:
    """在**项目成果表**对应乙类下追加一条：`| **F-N** | 标题 | 性质 | 怎么发现 | 证据 | 处置 |`。

    类别取值：`乙-1`（**我发现的**实现缺陷）／`乙-2`（**我发现的**判据与设计缺陷）／
             `乙-3`（★ **用户发现的**知识库缺失与用户侧观察）。
    ★★ **归类判据（用户 2026-10-14 定 —— 按「谁发现的」分，不按"错在哪一层"分）**：
        聚焦对象＝本项目，知识库只是参照物。**乙-3 是用户发现的**，不得把"我自己代码的缺陷"塞进去。

    ★ **为什么函数名从 `记发现` 改成 `记成果`**（2026-10-14，用户指出）：
        本项目原有一张 **「发现表」**（F-1~F-6），后来用户要求
        「**我个人倾向于这个发现表属于项目成果，应该更名为项目成果表，并且持续更新**」——
        于是它成了**项目成果表的乙类（发现与缺陷）**，**"发现表"这个独立表已不存在**。
        工具若继续叫 `记发现`，用的是**已被否掉的旧词**，会让人以为还有一张独立的"发现表"。
        所以改名为 `记成果`，并**保留"发现"作别名**（旧调用不断）。

    ⚠️ **边界（R-1 第 3 条，用户亲自立的硬要求）**：**「发现 ≠ 未决，必须分开登记」** ——
        本函数只写**成果表**；"已识别但还没到能解决的时候"的事应进**未决表**，
        **不得**混进这里，否则成果会被降级成待办、未决表也会失去"哪些到点了"的信号价值。
    """
    # ★ 锚点用**纯前缀**（2026-10-14 修）：原来写死完整标题（含旧措辞"用户侧观察"），
    #   标题一改锚点就失效。改为只认 `## 乙-x` 前缀 —— 措辞可演进，结构不能变。
    # ★★ 锚点表必须**覆盖现状全部分类**（2026-10-15 实测修复 —— F-41 的**复发形态**）：
    #   原表是**三分类时代的遗物**：只写了 乙-1／乙-2／乙-3，而 乙-3 的锚点直接指向
    #   最末的 `# 一句话总结`。**乙-4 节建立之后**，那个插入点就落进了**乙-4 段内**
    #   ⇒ `类别=乙-3` 的条目被写进乙-4（实测：F-69 声明乙-3、实际落在乙-4）。
    #   而更隐蔽的是：`_该行属于哪一节()` 也只认 乙-1/2/3 ⇒ **回读核对同样看不见乙-4**，
    #   把"乙-4"读成"乙-3"，于是**错位骗过了它自己的核对**并报"位置已独立核对"。
    #   ⇒ 判据：**分类增删时，锚点表与"落点判定"必须同步**；两者任一漏掉新分类，
    #     写入就会错位、且**错得看不出来**（两处口径一起错＝互相掩护）。
    锚 = {"乙-1": "## 乙-2", "乙-2": "## 乙-3", "乙-3": "## 乙-4",
         "乙-4": 成果表一句话总结锚点}.get(类别)
    if not 锚:
        return {"ok": False, "说明": "类别只能是 乙-1／乙-2／乙-3", "数据": {}, "证据": []}
    文 = 成果表.read_text(encoding="utf-8-sig")
    号 = _取下一个编号(文, "F", r"\*\*(F-\d+)\*\*")
    新段 = (f"| **{号}** ★ | **{标题.strip()}**（{datetime.now():%Y-%m-%d} 新增） | {性质.strip()} | "
           f"{怎么发现.strip()} | {证据.strip()} | {处置.strip()} |\n")

    # ★★ 列数一致性（2026-10-14 实测修复，**两版才对，第二版还错了一次**）：
    #   第一版：模板含「类别」列（6 格），而我当时以为表头是 5 列 → 判断错。
    #   第二版：加自带检查时**又硬编码 `!= 5`**，而模板实际是 6 格 → **拒绝一切写入**
    #           （S3 复跑 4 项全红，实测抓到）。
    #   ⇒ **第三版（本版）：不硬编码，读目标小节的真实表头**，用它的列数当判据。
    #     判据 = **新行的格数必须等于它要插入的那张表的表头格数**。
    def _目标表头格数() -> int | None:
        in节 = False
        for l in 文.splitlines():
            if l.startswith(f"## {类别}"):
                in节 = True
                continue
            if in节:
                if l.startswith("## ") or l.startswith("# "):
                    break
                if l.startswith("|") and ("发现" in l or "编号" in l):
                    return l.count("|") - 1
        return None

    _表头格 = _目标表头格数()
    _新行格 = 新段.count("|") - 1
    if _表头格 is not None and _新行格 != _表头格:
        return {"ok": False,
                "说明": f"内部错误：新行 {_新行格} 格 ≠ {类别} 表头 {_表头格} 列"
                        f"（拒绝写入，避免再次错位）",
                "数据": {"新行格数": _新行格, "表头格数": _表头格}, "证据": []}
    # 发现行要插在"该类的最后一行之后、下一个 `##` 之前"
    #   ★ 锚点用 **行首匹配**（`_找小节起点`），不用 `文.index()` ——
    #     实测 `文.index("## 乙-3")` 会命中**正文里提到的那个字符串**，把插点算错一节。
    i = _找小节起点(文, 锚)
    if i < 0:
        return {"ok": False, "说明": f"找不到锚点小节的**行首**：{锚}（不敢盲插）",
                "数据": {}, "证据": []}
    段 = 文[:i]                     # 该类的全文（到下一个 ## 之前）
    行尾 = 段.rstrip("\n")           # 去掉尾部空行后再找"最后一个表格行"
    m = list(re.finditer(r"^\|.*\|\s*$", 行尾, re.M))
    if not m:
        return {"ok": False, "说明": "在该类里没找到表格行，不敢盲插", "数据": {}, "证据": []}
    插点 = m[-1].end()               # ★ 插点必须在 `段`（而非 `行尾`）的坐标系里
    # ★ 这里第一版写了两行 `后文 = ...`，前一行是错的（切片算法绕错了）——
    #   后一行覆盖了它所以结果对，但**留着一行永不起作用的错代码**是隐患（读的人会以为它在生效）。
    #   现只留正确的那一行：**在"该类最后一个表格行"之后插入新行**。
    后文 = 文[:插点] + "\n" + 新段 + 文[插点:]
    前哈希, 前字节 = 文件sha256(成果表), len(文.encode("utf-8"))
    成果表.write_text(后文, encoding="utf-8", newline="\n")
    回 = 成果表.read_text(encoding="utf-8")
    # ★★ 语义位置核对（2026-10-14 新增，F-41 的正解）：
    #   **"写入成功"不等于"写对了地方"** —— 必须独立核对"新行落在哪一节"。
    #   注意这里**不用**上面算锚点的那个口径：锚点算的是"插哪儿"，
    #   这里核的是"**读回来它在哪**" —— 两者独立，否则又是"保险与操作共用同一口径"。
    落点 = _该行属于哪一节(回, 号)
    检查 = {"新行已写入": f"**{号}**" in 回,
           "原有内容未被删改": 回.replace("\n" + 新段, "", 1) == 文,
           "★ 落在指定小节": 落点 == 类别,
           "字节增量＝新行字节": len(回.encode("utf-8")) - 前字节 == len(("\n" + 新段).encode("utf-8"))}
    if not all(检查.values()):
        return {"ok": False,
                "说明": f"回读核对未通过：{检查}"
                        + (f"（要求落在 {类别}，实际落在 {落点} —— 已拒绝，请人工检查该文件）"
                           if 落点 != 类别 else ""),
                "数据": {"检查": 检查, "要求类别": 类别, "实际落点": 落点}, "证据": []}
    return {"ok": True, "说明": f"已登记成果 {号}（乙类：{类别}，**位置已独立核对**），写入并回读通过",
            "数据": {"编号": 号, "类别": 类别, "实际落点": 落点, "文件": str(成果表),
                    "前字节": 前字节, "后字节": len(回.encode("utf-8")), "回读检查": 检查},
            "证据": [{"文件": str(成果表), "编号": 号, "类别": 类别, "落点核对": "通过"}]}


def 记一件(类型: str, **参数) -> dict:
    """统一入口。类型：`要求`／`素材`／**`成果`**（`发现` 为兼容别名，等价）。

    参数按类型给（**扁平关键字**，便于工具层用 `**规范` 直接分发）：
        要求 : 正文=..., 标题=..., 原话=...
        素材 : 标题=..., 问题机制=..., 怎么发现=..., 数据证据=..., 怎么讲=...,
               岗位方向=..., 可承接追问=...
        成果 : 标题=..., 性质=..., 怎么发现=..., 证据=..., 处置=..., 类别=乙-1|乙-2|乙-3

    ⚠️ **`未决` 不在本版自动写入范围，理由（不是偷懒）**：
        `00_项目索引\\未决与待办.md` 里有 **11 张列数各不相同的子表**
        （实测列数：7／5／5／5／4／3／4／4／4／5 …），每张的身份／状态写法还不同。
        自动插入要猜"该进哪张表、补哪几列"——**猜错的概率高于省下的力气**，
        而且改坏的是**唯一登记处**。所以：**未决仍由人写**，工具只负责其余三处。
    """
    表 = {"要求": 记要求, "素材": 记素材, "成果": 记成果, "发现": 记成果}
    if 类型 == "未决":
        return {"ok": False,
                "说明": "`未决` 不自动写入（该表跨 11 张子表、列数各异，自动插入易改坏唯一登记处）"
                        "—— 请人工写入 `00_项目索引\\未决与待办.md`",
                "数据": {}, "证据": []}
    if 类型 not in 表:
        return {"ok": False, "说明": f"类型只能是 要求／素材／成果（收到 {类型}）", "数据": {}, "证据": []}
    r = 表[类型](**参数)
    r["工具"] = "记一件"
    r["费用"] = {"embedding": "0", "生成": "0"}
    return r


