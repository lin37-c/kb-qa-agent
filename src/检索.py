def 解析分组(问题: str, 分组表: dict[str, tuple[str, ...]] | None = None) -> tuple[str, str]:
    """从提问开头识别分组触发词。返回（分组, 去掉触发词后的问题）。

    例："技能库 怎么写测试报告" → ("技能", "怎么写测试报告")
    识别不到就用默认分组。
    ★ 只认**开头**的词 —— 避免句中出现"技能"两字就误切换（如"我的技能库怎么检索"）。
    """
    t = 问题.strip()
    for 词, 组 in sorted(分组触发词.items(), key=lambda kv: -len(kv[0])):
        if t.startswith(词):
            余 = t[len(词):].lstrip("　 ：:，,。")
            if 余:
                return 组, 余
    return 默认分组, t


def 猜分组(问题: str, 元数据: list[dict], 粗召回=(None, None)) -> tuple[str | None, list[str]]:
    """自动判房间：决定"这个问题该去哪个房间找"。

    目的（用户 2026-10-13 要求）：**用户不用记前缀**。
    一个中文提问者不会知道要打「技能库」——他只会问「怎么用 pytest 写测试」。

    --- 为什么最终用的是「粗召回 + 多房间并集」，而不是"选一个房间" ---

    最初实现是三级词表（组名 → 顶层目录名 → 二级目录名）。**2026-10-13 实测暴露
    它修不动**：全包扩索引后 4 题判错房间，而这几题的提问词**字面上打不中目录名**：

        缺陷单怎么写      → 库里是 `05_缺陷分析与管理/core-bug_report/`（问题里没有"缺陷分析与管理"）
        浏览器怎么自动化操作 → 库里是 `02_浏览器与取证/browser/`
        Excel 表格怎么读写  → 库里是 `01_文档处理/spreadsheets/`（**库里是英文**）
        思维导图怎么生成    → 库里是 `04_测试点与XMind/core-xmind_file/`

    词表匹配的根本缺陷：**词表要人来维护，改一次语料就得改一次代码**；
    而它要匹配的恰恰是"提问用词"与"目录命名"之间的语义落差——**那正该交给向量去算**。

    改成"粗召回定房间"后好了 3 题，但**又暴露了更深的问题：不该只选一个房间**。
    2026-10-13 实测「改文件之前要先做什么」：

        房间        最高分    前3均
        维护工具    0.6258    0.5975   ← 最高分赢
        规则体系    0.6098    0.6065   ← 前3均赢

    **两个指标给出相反结论** —— 说明"选一个房间"这件事本身不可靠。
    而「浏览器怎么自动化操作」更明显：**规则体系（讲工具使用规则）与技能库
    （讲怎么做）给的都相关，两个都是用户要的**。

    所以最终判据：**多房间并集**
      · 取粗召回里**达到阈值_低**的房间
      · 且其最高分**不低于全局最高分 × 并集系数**（默认 0.90）
      · 把这些房间的前缀**并起来**当成一个虚拟房间去搜
      · 若没有任何房间达标 → 返回 None，走默认分组

    这样：判"该搜哪些房间"而不是"该搜哪个房间"，**误判的代价从"搜错地方"
    降级为"多搜了一个地方"**。
    """
    分组表, 粗 = 粗召回
    if 粗 and 分组表 is not None:
        # ① 每个房间在粗召回里的最高分
        房间分: dict[str, float] = {}
        for h in 粗:
            顶层 = 顶层目录(h["来源文件"])
            名 = "根目录" if 顶层 == "" else 顶层
            for g, 前缀 in 分组表.items():
                if g == "全库":
                    continue
                规 = _规范前缀(前缀)
                if 规 and (f"{顶层}/" in 规 or (顶层 == "" and "" in 规)):
                    名 = g
                    break
            房间分[名] = max(房间分.get(名, -1.0), h["相似度"])
        if not 房间分:
            return None, []
        全局最高 = max(房间分.values())
        if 全局最高 < 阈值_低:
            return None, []          # 哪个房间都没到阈值 → 不猜，走默认组
        # ② 多房间并集：达到阈值 且 不低于全局最高 × 系数
        选中 = [g for g, s in 房间分.items() if s >= 阈值_低 and s >= 全局最高 * 并集系数]
        # 按分数降序，让最相关的房间排前面（并集键里保持这个顺序便于人读）
        选中.sort(key=lambda g: -房间分[g])
        if not 选中:
            return None, []
        依据 = [f"{g}({房间分[g]:.4f})" for g in 选中]
        return "并集:" + "＋".join(选中), 依据

    # 兜底：词表匹配（保留原三级判据；粗召回不可用时才走这里）
    for 名 in 精确分组:
        if 名 in ("全库", "规则体系"):
            continue
        if 名 and 名 in 问题:
            return 名, [名]
    for 名 in 自动分组定义(元数据):
        if 名 == "根目录":
            continue
        if 名 and 名 in 问题:
            return 名, [名]
    二级索引: dict[str, str] = {}
    for d in 元数据:
        段 = d["来源文件"].replace("\\", "/").split("/")
        if len(段) >= 2:
            顶层, 二级 = 段[0], 段[1]
            净 = 二级.split("_", 1)[1] if "_" in 二级 else 二级
            if len(净) >= 2 and 净 not in 二级索引:
                二级索引[净] = 顶层
    for 词 in sorted(二级索引, key=len, reverse=True):
        if 词 in 问题:
            顶层 = 二级索引[词]
            for 名, 前缀 in 精确分组.items():
                if 名 != "全库" and _规范前缀(前缀) and 顶层 + "/" in _规范前缀(前缀):
                    return 名, [f"{词}（属 {顶层}）"]
            return 顶层, [f"{词}（属 {顶层}）"]
    return None, []


def 默认分组最高分(纯问题: str, 查询文本: str, 分组表: dict[str, tuple[str, ...]],
              缓存: dict | None = None) -> float | None:
    """算默认分组下的最高相似度（用来判断"该不该切房间"）。

    与主检索共用**同一个查询向量**——调用方把 `查询文本` 传进来，
    这里复用 `向量化单条` 的缓存（同一文本第二次调用命中内容指纹缓存，不花钱）。
    """
    if 缓存 is not None and "分" in 缓存:
        return 缓存["分"]
    m, 元数据 = _载库()
    表 = 分组表
    if 默认分组 not in 表:
        return None
    前缀 = _规范前缀(表[默认分组])
    保留 = [i for i, d in enumerate(元数据) if _命中过滤(d["来源文件"], 前缀)] if 前缀 else list(range(len(元数据)))
    if not 保留:
        return None
    qv = 归一化(向量化.向量化单条(查询文本, 场景="M3检索"))
    分 = m[保留] @ qv
    # ★ 用「有效分」（含数据登记类降权）——与主检索、粗召回同口径。
    #   这是"该不该切房间"的判据，必须与最终排序看到的分数一致，
    #   否则会出现"判据说已达可信命中、但排序里它其实已被降权"的矛盾。
    for i, gi in enumerate(保留):
        分[i] *= 有效权重(元数据[gi]["来源文件"], 元数据[gi].get("文本", ""))
    if 缓存 is not None:
        缓存["分"] = float(分.max())
    return float(分.max())


def 并集前缀(名: str, 分组表: dict[str, tuple[str, ...]]) -> tuple[str, ...]:
    """把「并集:A＋B」这种虚拟房间名解析成合并后的前缀元组。"""
    if not 名.startswith("并集:"):
        return _规范前缀(分组表.get(名, ()))
    出: list[str] = []
    for g in 名[len("并集:"):].split("＋"):
        前缀 = _规范前缀(分组表.get(g, ()))
        for p in 前缀:
            if p not in 出:
                出.append(p)
    return tuple(出)


def _载入带过滤(分组: str, 分组表: dict[str, tuple[str, ...]] | None = None):
    """载入向量库，按分组过滤行。返回（矩阵, 元数据子集, 全部元数据, 空房间原因）。

    ★ 支持「并集:A＋B」这种虚拟房间名（自动判房间可能返回它，见 猜分组）。
    """
    m, 元数据 = _载库()
    表 = 分组表 or 全部分组(元数据)
    if 分组 not in 表 and not 分组.startswith("并集:"):
        raise ValueError(f"未知分组：{分组}（可选：{'／'.join(表)}）")
    前缀 = 并集前缀(分组, 表)
    if not 前缀:
        return m, 元数据, 元数据, ""
    保留 = [i for i, d in enumerate(元数据) if _命中过滤(d["来源文件"], 前缀)]
    if not 保留:
        # ★ 空房间不是错误，是"这个房间还没建索引"（分期扩索引期间会真实出现）。
        #   抛异常会让调用方炸掉；返回空集＋原因，调用方就能照常给出"库中没有"的判定。
        #   （实测：分期扩索引前，插件/技能目录/维护工具/维护审计/根目录 五组都是空的。）
        return (m[:0], [], 元数据, f"分组「{分组}」目前没有内容（前缀 {前缀}）——该区域尚未入库")
    return m[保留], [元数据[i] for i in 保留], 元数据, ""


# ---------- 二阶段重排（2026-10-18 引入，未决 U-52）----------
#
# 为什么要有这一层（这是 M7 第 1 步量出来的，不是"业界都这么做"）：
#   纯向量的天花板不在"算得准不准"，而在"**它只管像不像，不管够不够用**"。
#   M7 实测：34 道未命中里，**25 道的正确块在全库里排前 100，其中 14 道排前 20** ——
#   也就是说向量早就把它们捞上来了，是**房间过滤**把它们关在门外。
#   ⇒ 重排的价值不在"救那些排 500 名以后的"，而在"**让我们敢用更宽的候选池**"：
#     池子放宽（全库），再用重排把噪声压下去。
#
# ★ 单独一本账：rerank 与 embedding 是两笔钱、两个单价。并进同一份账本会把
#   `向量化.读账本()` 的 embedding 成本算错（它一律按向量单价折算）。
重排账本路径 = 配置.缓存目录 / "重排账本.jsonl"


def _记重排用量(场景: str, tokens: int) -> None:
    """把 rerank 的真实 token 用量追加进**独立**账本。"""
    重排账本路径.parent.mkdir(parents=True, exist_ok=True)
    条目 = {
        "时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        "场景": 场景,
        "模型": 配置.重排模型,
        "tokens": tokens,
        "费用_元": round(tokens / 1_000_000 * 配置.重排单价_元每百万token, 8),
    }
    with 重排账本路径.open("a", encoding="utf-8") as f:
        f.write(json.dumps(条目, ensure_ascii=False) + "\n")


def 读重排账本() -> dict:
    """汇总重排账本：调用次数、总 token、总费用。"""
    次数 = tokens = 0
    if 重排账本路径.exists():
        for line in 重排账本路径.read_text(encoding="utf-8").splitlines():
            if line.strip():
                d = json.loads(line)
                次数 += 1
                tokens += d.get("tokens", 0)
    return {"次数": 次数, "tokens": tokens,
            "费用_元": round(tokens / 1_000_000 * 配置.重排单价_元每百万token, 6)}


def 重排(问题: str, 候选: list[dict], 取前: int | None = None,
        场景: str = "M3重排", 重试: int = 2) -> tuple[list[dict], dict]:
    """把「查询 ＋ 候选块」交给 **阿里 qwen3-rerank** 重新打分排序。

    ★★ 2026-10-24 从智谱 rerank 换到阿里，两个坑必须记住：

       ① **智谱的 `return_raw_scores` 参数在这里不存在**。智谱默认返回的是"批内归一化"分数，
          会饱和到 1.000000；阿里 qwen3-rerank 返回的是**归一化到 0~1 的相关性分**（实测 0.15~0.9），
          本身有区分度，**不需要也不支持 raw scores 开关**。

       ② **必须分批**：qwen3-rerank 单次上下文上限 **3 万 token**（query ＋ 全部 documents），
          100 条候选约 5.9 万字符 ⇒ 一定超限。已实测「同一条文档放在不同批里分数完全一致」
          （0.904989 四次相同）⇒ 分批打分再合并是**合法**的，不是近似。

    ★ `重排分` 量纲与余弦完全不同（0~1 vs 0~1 但语义不同），**不得**拿去和向量阈值比。

    参数
        问题 : 用**用户原话**（纯问题），扩展词对重排模型是噪声。
        候选 : 已按向量分排好序的块列表；函数会把 `position+1` 记成 `重排前位次`。
        取前 : 让接口返回前几条（默认全部）。

    返回（重排后的块列表, 用量字典）
    """
    if not 候选:
        return [], {}
    取前 = 取前 or len(候选)
    key = 向量化.取密钥()
    t0 = time.time()

    # ---- 分批打分：每批 ≤ 配置.重排批量 条 ----
    打分: list[tuple[float, int]] = []          # (重排分, 候选内位置)
    tokens = 0
    批大小 = getattr(配置, "重排批量", 40)
    for i in range(0, len(候选), 批大小):
        批 = 候选[i : i + 批大小]
        payload = {
            "model": 配置.重排模型,
            "input": {"query": 问题, "documents": [h["文本"] for h in 批]},
            "parameters": {"top_n": len(批), "return_documents": False},
        }
        last: Exception | None = None
        ok = False
        for 试 in range(重试 + 1):
            try:
                r = requests.post(
                    配置.重排地址,
                    headers={"Authorization": f"Bearer {key}",
                             "Content-Type": "application/json; charset=utf-8"},
                    data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
                    timeout=90,
                )
                if r.status_code != 200:
                    raise RuntimeError(f"HTTP {r.status_code}: {r.text[:300]}")
                j = r.json()
                tokens += int((j.get("usage") or {}).get("total_tokens", 0))
                for it in j["output"]["results"]:
                    打分.append((float(it["relevance_score"]), i + int(it["index"])))
                ok = True
                break
            except Exception as e:  # noqa: BLE001
                last = e
                if 试 < 重试:
                    time.sleep(1.5 * (试 + 1))
        if not ok:
            raise RuntimeError(f"重排连续 {重试 + 1} 次失败：{last}")

    _记重排用量(场景, tokens)
    打分.sort(key=lambda kv: -kv[0])            # 跨批合并：分数已是同一量纲，可直接排

    出: list[dict] = []
    for 分, 位 in 打分[:取前]:
        d = dict(候选[位])
        d["重排前位次"] = 位 + 1                  # 候选是按向量分排好的 ⇒ +1 就是向量名次
        d["重排分"] = round(分, 6)
        出.append(d)
    return 出, {"tokens": tokens, "耗时秒": round(time.time() - t0, 2),
                "候选数": len(候选), "批数": (len(候选) + 批大小 - 1) // 批大小}




def 检索(问题: str, 取前: int = 5, 分组: str | None = None, 用扩展: bool = True,
        自动判房间: bool = False,
        用重排: bool = False, 重排池: str = "分组", 重排候选数: int = 50) -> dict:
    """检索主函数。返回结构化结果（含判定、出处、原始数值）。

    参数
        分组      : 显式指定分组；None 时先用问题前缀，再用默认分组
        自动判房间 : True 时，若问题里出现别的组名，自动切到那个组（用户不用打前缀）
        用重排    : ★ 默认 **False**。必须默认关 —— 一开就会多一次付费调用，
                    若默认开，所有历史账目与结论都失真。
        重排池    : `"分组"`＝在路由器选中的房间内取候选（保底、改动最小）；
                    `"全库"`＝不按房间过滤，全库取候选（M7 实测上限高 19 个百分点）。
        重排候选数 : 送多少条给 rerank（默认 50；接口上限 128 条）。

    返回字段
        问题 / 分组 / 分组来源 / 扩展词 / 命中数 / 判定 / 最高相似度 / 阈值说明 / 结果列表
        ＋ 用重排时为：重排池 / 重排候选数 / 重排用量；每条结果多 `重排前位次`、`重排分`

    ★ 判定口径**不因重排而改变**：`最高相似度` 取的是**重排前**的向量最高分，
      重排只改顺序、不参与"库中有没有相关内容"的判定（两者不是同一个量纲）。
    """

    _, 元数据全 = _载库()
    表 = 全部分组(元数据全)

    前缀分组, 纯问题 = 解析分组(问题)
    分组来源 = "问题前缀" if 纯问题 != 问题.strip() else "默认"
    选分组 = 分组 or 前缀分组

    if 分组 is None and 自动判房间 and 分组来源 == "默认":
        猜, 依据 = 猜分组(纯问题, 元数据全)
        if 猜:
            选分组, 分组来源 = 猜, f"自动判房间（依据：{'、'.join(依据)}）"

    if 选分组 not in 表:
        raise ValueError(f"未知分组：{选分组}（可选：{'／'.join(表)}）")

    # ★★ 2026-10-22 修（F-101）：**分组照切，查询不切**。
    #   原来这里用的是 `纯问题`（被 `解析分组` 剥掉开头分组词之后的文本）。
    #   实测代价：124 道题里有 14 道的问句**本身**就以「技能／维护工具／插件…」开头，
    #   被当成分组前缀剥掉 ⇒「技能目录与依赖是怎么组织的」变成「与依赖是怎么组织的」。
    #   对照实验（同一批题、同样的池子与重排，只把被吃掉的词还回去）：
    #   那 14 道命中 **6 → 11**，其中 5 道由未命中翻成命中。
    #   ★ 分组判定**不动** —— 这 14 道切出来的房间其实都是对的，坏的只是查询文本。
    查询文本, 扩展词 = 扩展查询(问题.strip()) if 用扩展 else (问题.strip(), [])

    # ★ 查询向量只算一次，主检索与"粗召回定房间"共用 —— 不多调接口、不多花钱。
    qv = 归一化(向量化.向量化单条(查询文本, 场景="M3检索"))

    # 「粗召回定房间」（需要在选房间之前做，否则不知道进哪个房间）：
    #   用同一个查询向量在全库上取前 N，看高分块落在哪个房间。
    #   只有当调用方没显式指定分组、也没打前缀时才做。
    # ★ 粗召回的分**必须用降权后的有效分** —— 否则台账 JSON（如来源与适配清单）
    #   会以 0.6506 的高分把房间判成"规则体系"，而技能库的真答案（0.6267）永远浮不上来。
    粗召回结果 = None
    if 选分组 == 前缀分组 and 分组来源 == "默认":
        _m_all, _meta_all = _载库()
        _原始 = _m_all @ qv
        _权重 = np.array([有效权重(_meta_all[i]["来源文件"], _meta_all[i]["文本"])
                       for i in range(len(_meta_all))])
        _有效 = _原始 * _权重
        _序 = np.argsort(-_有效)[:12]
        粗召回结果 = []
        for _i in _序:
            _d = dict(_meta_all[int(_i)])
            _d["相似度"] = round(float(_有效[int(_i)]), 4)
            _d["原始相似度"] = round(float(_原始[int(_i)]), 4)
            粗召回结果.append(_d)

    if 分组 is None and 自动判房间 and 分组来源 == "默认":
        # ★ 切换门槛（2026-10-13 实测加入）：**默认分组已经给到"可信命中"就不切房间**。
        #
        #   为什么必须加这一条（实测数据）：
        #     切换到并集后，技能类 3/7 → **7/7**、冷门房间 0/3 → **3/3**，
        #     但规则类 7/8 → **5/8** —— 并集把技能库的块混进来，
        #     把规则类的正确答案挤出了前 10（例：「提交代码之前需要出什么报告」
        #     默认分 0.6683 排第 1，走并集后**掉出前 10**）。
        #
        #   判据（2026-10-14 修正为两条，理由见下）：
        #     · 默认分组最高分 ≥ 阈值_高（0.58）**且** 不低于"其他房间最高分 × 显著系数"
        #       → 已在"可信命中"档、且别人没明显更好 → **留在默认组**
        #     · 否则 → **切到自动判出的房间**
        #
        #   为什么从"只看 ≥0.58"改成"两条"（实测依据）：
        #     「缺陷单怎么写」默认组（规则体系）拿到 0.5874 ≥ 0.58 → 按旧规则不切房间，
        #     但技能库有 **0.6593**（`core-bug_report` 缺陷单撰写）—— 明显更好却被挡住。
        #     所以除了"够不够可信"，还要看"**别人是不是显著更好**"。
        #
        #   显著系数 0.92 的取值校验（用当前 18 题反查，逐题确认不误判）：
        #     · 「提交代码之前需要出什么报告」默认 0.7644 ／ 别处 0.6792
        #       → 0.6792×0.92=0.6249 ≤ 0.7644 → **留默认组** ✓（该题答案确实在规则）
        #     · 「浏览器怎么自动化操作」默认 0.6506 ／ 别处 0.6359
        #       → 0.6359×0.92=0.5850 ≤ 0.6506 → **留默认组** ✓
        #     · 「缺陷单怎么写」默认 0.5874 ／ 别处 0.6593
        #       → 0.6593×0.92=0.6066 > 0.5874 → **切房间** ✓（该题答案确实在技能）
        #
        #   ⚠️ 诚实标注：0.92 与 `并集系数` 0.90 一样，**都是在当前 18 题上取值、
        #      未经独立验证**。正式标定留 M7 的独立评测集（未决 U-01）。
        _分默认 = 默认分组最高分(纯问题, 查询文本, 表)
        _别处最高 = max((h["相似度"] for h in (粗召回结果 or [])), default=0.0)
        _阈值显著 = _别处最高 * 显著系数
        if (_分默认 is not None and _分默认 >= 阈值_高 and _分默认 >= _阈值显著):
            分组来源 = (f"默认（默认组已达可信命中 {_分默认:.4f} ≥ {阈值_高}，"
                     f"且不低于其他房间最高 {_别处最高:.4f}×{显著系数}={_阈值显著:.4f}，故不切房间）")
        else:
            猜, 依据 = 猜分组(纯问题, 元数据全, 粗召回=(表, 粗召回结果))
            if 猜:
                选分组 = 猜
                _因 = (f"默认组最高 {_分默认:.4f}"
                      + ("＜阈值_高 " + str(阈值_高) if (_分默认 or 0) < 阈值_高
                         else f"＜其他房间最高 {_别处最高:.4f}×{显著系数}={_阈值显著:.4f}"))
                分组来源 = f"自动判房间（{_因}；依据：{'、'.join(依据)}）"

    if 选分组 not in 表 and not 选分组.startswith("并集:"):
        raise ValueError(f"未知分组：{选分组}（可选：{'／'.join(表)}）")

    # ★ 候选池（2026-10-18）：
    #   默认 ＝ 路由器选中的房间（与改动前**逐字节等价**）；
    #   `全库` ＝ 不按房间过滤，全库取前 N。只在 `用重排` 时才有意义：
    #   重排的任务是"从宽池子里挑"，池子越宽它越有用；而房间过滤会在重排之前
    #   就把正确块丢掉（M7 实测 34 道未命中里，25 道金块在全库前 100、14 道在前 20）。
    用全库池 = 用重排 and 重排池 == "全库"
    if 用全库池:
        _m, _meta = _载库()
        m, 子元数据, 全元数据, 空房间原因 = _m, _meta, _meta, ""
    else:
        m, 子元数据, 全元数据, 空房间原因 = _载入带过滤(选分组, 表)
    原始分 = m @ qv
    # ★ 排序与判定都用「有效分」＝ 原始分 × 权重（数据登记类打折）。
    #   台账类仍留在库里、仍可被检索到（"资产包有哪些文件/来源"要能答），
    #   只是不再霸占前几名、也不再阻止"切房间"。
    权重 = np.array([有效权重(d["来源文件"], d.get("文本", "")) for d in 子元数据])
    分 = 原始分 * 权重
    # 要重排就先多捞一些交给它（重排只能重排"已经召回到的"，捞不到就救不回）
    候选数 = max(取前, 重排候选数) if 用重排 else 取前
    序 = np.argsort(-分)[:候选数]

    结果 = []
    for i in 序:
        d = dict(子元数据[int(i)])
        d["相似度"] = round(float(分[int(i)]), 4)
        _原 = float(原始分[int(i)])
        if abs(_原 - float(分[int(i)])) > 1e-9:
            d["原始相似度"] = round(_原, 4)      # 被降权的块：把原始分也留着，便于核对
        结果.append(d)

    # ★ 先取「重排前」的最高向量分 —— 判定用它，重排不许改判定（两者不是同一量纲）
    最高 = 结果[0]["相似度"] if 结果 else 0.0

    重排用量: dict = {}
    if 用重排 and 结果:
        # ★ 重排查询同样用**原话**（2026-10-22，与上面的 F-101 同因：剥前缀会残句）
        结果, 重排用量 = 重排(问题.strip(), 结果, 取前=len(结果), 场景="M3重排")
        结果 = 结果[:取前]

    # ★ 闸门（2026-10-23）：用重排时按「重排尺度」判，否则仍按向量尺度判（旧账不失真）
    if 用重排 and 结果:
        闸门分 = max(float(h.get("重排分") or 0.0) for h in 结果)
        闸门尺度 = "重排"
        阈高, 阈低 = 重排阈值_高, 重排阈值_低
        阈说明 = 重排阈值说明
    else:
        闸门分, 闸门尺度 = 最高, "向量"
        阈高, 阈低 = 阈值_高, 阈值_低
        阈说明 = 阈值说明

    # ★ 编号存在性核验（2026-10-24）：在闸门之前先看"问题里点的编号存不存在"
    _编号过, _编号说明 = _核禁令编号(问题)

    if not _编号过:
        判定 = _编号说明
    elif 空房间原因:
        判定 = f"该区域尚未入库（{空房间原因}）"
    elif 闸门分 >= 阈高:
        判定 = "可信命中"
    elif 闸门分 >= 阈低:
        判定 = "弱相关（仅供参考，建议换个说法再问）"
    else:
        判定 = "库中没有相关内容（检索系统不应在此硬答）"

    # ★ 唯一裁决点（2026-10-23，F-106）：能不能作答，只在这里算一次；
    #   生成层只读这个布尔值，不许自己再比一次阈值（否则规则一改就打架）。
    可否作答 = _编号过 and (not 空房间原因) and (闸门分 >= 阈低)

    return {
        "问题": 问题,
        "纯问题": 纯问题,
        "分组": 选分组,
        "分组来源": 分组来源,
        "空房间原因": 空房间原因,
        "扩展词": 扩展词,
        "查询文本": 查询文本,
        "命中数": len(结果),
        "判定": 判定,
        "可否作答": 可否作答,
        "闸门分": round(float(闸门分), 4),
        "闸门尺度": 闸门尺度,
        "闸门阈值": {"高": 阈高, "低": 阈低},
        "最高相似度": 最高,
        "阈值说明": 阈说明,
        "候选池": len(子元数据),
        "库总量": len(全元数据),
        "用重排": 用重排,
        "重排池": 重排池 if 用重排 else "",
        "重排用量": 重排用量,
        "结果": 结果,
    }


def 格式化(结果: dict, 正文长度: int = 120) -> str:
    """把检索结果排成人能读的样子（含出处）。"""
    L = []
    L.append(f"提问：「{结果['问题']}」")
    L.append(f"  分组   : {结果['分组']}（候选池 {结果['候选池']} 块 / 库总量 {结果['库总量']} 块）")
    if 结果["扩展词"]:
        L.append(f"  查询扩展: 命中 {('、'.join(结果['扩展词']))} → 已把等价说法补进查询")
    L.append(f"  判定   : {结果['判定']}（闸门 {结果.get('闸门分', 结果['最高相似度'])}"
             f"／{结果.get('闸门尺度', '向量')}尺度；阈值 {结果.get('闸门阈值', {})}）")
    L.append(f"  向量最高: {结果['最高相似度']}（仅供核对，不参与判定）")
    L.append(f"  阈值说明: {结果['阈值说明']}")
    for i, h in enumerate(结果["结果"], 1):
        正文 = h["文本"].replace("\n", " ⏎ ")
        if len(正文) > 正文长度:
            正文 = 正文[:正文长度] + "…"
        L.append("")
        L.append(f"  {i}. [{h['相似度']:.4f}] {h['来源文件']}")
        L.append(f"     标题: {h['标题路径'] or '(无标题)'}   行 {h['起始行']}–{h['结束行']}   字符 {h.get('字符数', len(h['文本']))}")
        L.append(f"     内容: {正文}")
    return "\n".join(L)
