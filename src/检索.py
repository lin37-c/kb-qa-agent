# ★ 实测依据：G2a「编号不存在」组 59 道，失败 32 道多为"顺着不存在的编号编内容"。
_禁令上限缓存: dict = {"值": None}


def _禁令序号上限() -> int:
    if _禁令上限缓存["值"] is None:
        _, 元 = _载库()
        ns = []
        for d in 元:
            for m in re.findall(r"P-0*(\d{1,3})(?!\d)", d.get("文本", "")):
                ns.append(int(m))
        _禁令上限缓存["值"] = max(ns) if ns else 0
    return _禁令上限缓存["值"]


def _核禁令编号(问题: str) -> tuple[bool, str]:
    """问题里点了 P-nn 就核一遍：序号超过库中最大值 ⇒ 该编号不存在。"""
    上限 = _禁令序号上限()
    for m in re.finditer(r"P-0*(\d{1,3})(?!\d)", 问题):
        if int(m.group(1)) > 上限:
            return False, f"问题里的 {m.group(0)} 在库中不存在（库中禁令编号只到 P-{上限:02d}）"
    return True, ""



