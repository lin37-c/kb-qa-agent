def 是数据登记类(来源文件: str, 文本: str = "") -> bool:
    """判断一块内容是不是「数据登记类」（清单/登记/快照/二进制目录条目）。

    是 → 检索时降权；但**仍留在索引里**（保证"资产包有哪些文件/来源"可答）。
    """
    if 文本.startswith("【") and "内容未纳入文本索引" in 文本:
        return True                    # 二进制文件的目录条目
    if any(p in 来源文件 for p in 台账保护):
        return False
    if any(p in 来源文件 for p in 台账路径特征):
        return True
    if 来源文件.endswith(".json") and any(p in 来源文件 for p in 台账文件特征):
        return True
    return False


def 有效权重(来源文件: str, 文本: str = "") -> float:
    """返回该块的排序权重（1.0 = 不降权）。"""
    if not 是数据登记类(来源文件, 文本):
        return 1.0
    return 台账系数 + (1.0 - 台账系数) * 台账混合


