# ---------- 禁令编号存在性核验（2026-10-24，降幻觉） ----------
# ★ 为什么只核 P 家族：禁令编号是**闭集**（库中只到 P-14），可判定；
#   而 R-7.3／R-7.4／U-50 这类是**项目级编号**，库里没有不等于不存在（它们在本项目文档里），
