# ---------- 自动分组（2026-10-13 新增） ----------
# 为什么要：原分组手工写死只覆盖 3 个顶层目录；扩到整个资产包（569 文件 / 8 个顶层目录）
# 后手工维护不成立。改成"库里出现什么顶层目录，就自动有什么组"——**新增目录不用改代码**。
def 顶层目录(相对路径: str) -> str:
    """取来源文件的顶层目录。语料根下的文件（无斜杠）返回 ""。"""
    s = 相对路径.replace("\\", "/")
    if "/" not in s:
        return ""
    return s.split("/", 1)[0]


def 自动分组定义(元数据: list[dict]) -> dict[str, tuple[str, ...]]:
    """从库里实际出现的顶层目录自动生成分组表。"""
    表: dict[str, tuple[str, ...]] = {}
    for d in 元数据:
        顶层 = 顶层目录(d["来源文件"])
        if 顶层 == "":
            表.setdefault("根目录", ("",))
        else:
            表.setdefault(顶层, (f"{顶层}/",))
    return 表


def 全部分组(元数据: list[dict] | None = None) -> dict[str, tuple[str, ...]]:
    """精确分组 ＋ 自动分组 的合并结果。

    合并口径（避免同一个房间出现两次）：
      · 精确分组里已**完整覆盖**的目录，不再另出自动组
        （例：「规则体系」已含 `02_规则/`，就不再单出一个「02_规则」组）
      · 精确分组没覆盖到的目录，自动成组 —— 这是"新增目录不用改代码"的落实
    """
    表: dict[str, tuple[str, ...]] = {}
    已覆盖: set[str] = set()
    for v in 精确分组.values():
        已覆盖.update(_规范前缀(v))
    if 元数据:
        for 名, 前缀 in 自动分组定义(元数据).items():
            if 名 in 精确分组:
                continue
            if all(p in 已覆盖 for p in 前缀):
                continue           # 已被精确分组完整覆盖，不重复成组
            表[名] = 前缀
    表.update(精确分组)
    表.setdefault("全库", ())
    return 表


def _规范前缀(前缀) -> tuple[str, ...]:
    """把分组值规范成元组，兼容旧的字符串写法。"""
    if 前缀 is None:
        return ()
    if isinstance(前缀, str):
        return (前缀,) if 前缀 else ()
    return tuple(前缀)


def _命中过滤(来源文件: str, 前缀: tuple[str, ...]) -> bool:
    """空元组 = 不过滤；("",) = 只匹配根目录文件；其余为目录前缀。"""
    if not 前缀:
        return True
    s = 来源文件.replace("\\", "/")
    for p in 前缀:
        if p == "":
            if "/" not in s:
                return True
        elif s.startswith(p):
            return True
    return False


