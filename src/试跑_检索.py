# -*- coding: utf-8 -*-
"""M3 试跑：验证检索层的四项增强（来源过滤 / 查询扩展 / 阈值 / 出处）。

试跑设计原则：**每一项增强都要有"它解决的那个具体问题"做对照**，
不能只说"跑通了"。所以下面每段都写明：在验证什么、期望看到什么。

用法：
    python 试跑_检索.py            # 全部用例
    python 试跑_检索.py <问题>     # 单个问题
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

# 搜索路径两处：
#   ① 本文件目录 —— 命中"正在被验证的候选版 检索.py"
#   ② 正式位置 src\ —— 让 检索.py 里的 import 配置/向量化/缓存/入库 命中已发布依赖
项目src = Path(r"<workspace>\01_项目\DeepSeek Harness专用\LLM知识库检索与工具调用\02_项目源码与工程\src")
for p in (str(Path(__file__).resolve().parent), str(项目src)):
    if p not in sys.path:
        sys.path.insert(0, p)

import 检索 as R


def 段(标题: str) -> None:
    print("\n" + "=" * 78)
    print(标题)
    print("=" * 78)


def 用例(问题: str, 说明: str, 期望: str, 取前: int = 3) -> bool:
    print(f"\n【{说明}】")
    print(f"  期望：{期望}")
    try:
        r = R.检索(问题, 取前=取前)
    except Exception as e:  # noqa: BLE001
        print(f"  ❌ 异常：{e}")
        return False
    print(R.格式化(r, 正文长度=100))
    return True


def main() -> int:
    单问 = sys.argv[1] if len(sys.argv) > 1 else None
    if 单问:
        r = R.检索(单问, 取前=5)
        print(R.格式化(r, 正文长度=200))
        return 0

    print("=" * 78)
    print("M3 检索层试跑")
    print("=" * 78)
    print(f"阈值_高 = {R.阈值_高}  ｜  阈值_低 = {R.阈值_低}")
    print(f"说明     = {R.阈值说明}")
    print(f"默认分组 = {R.默认分组}  ｜  可选分组 = {'／'.join(R.来源分组)}")

    # ---------- 增强① 来源过滤（B-2）----------
    段("增强① 来源过滤（B-2）：默认只查规则；打前缀可切换")
    用例("改文件之前要先做什么",
         "默认分组（不打前缀）",
         "默认走「规则」组，且正确内容应排在前面",
         )
    用例("技能库 怎么写测试报告",
         "打「技能库」前缀切换分组",
         "分组变为「技能」，命中的来源文件应以 01_技能/ 开头",
         )
    用例("全库 测试报告模板长什么样",
         "打「全库」前缀不过滤",
         "分组变为「全库」，候选池 = 库总量",
         )

    # ---------- 增强② 查询扩展（U-03）----------
    段("增强② 查询扩展：M2 里召不回的「候选区」现在应能召回")
    用例("候选区和正式区的区别是什么",
         "提问用了语料里不存在的词（U-03 的原始症状）",
         "扩展词命中「候选区」「正式区」；应召回到讲候选/正式发布物的内容，而不是无关的边界值分类",
         )

    # 对照：关闭扩展，看差异
    print("\n【对照：同一问题，关闭查询扩展】")
    try:
        r0 = R.检索("候选区和正式区的区别是什么", 取前=3, 用扩展=False)
        print(f"  判定：{r0['判定']}（最高 {r0['最高相似度']}）")
        for i, h in enumerate(r0["结果"], 1):
            print(f"  {i}. [{h['相似度']:.4f}] {h['来源文件']} > {h['标题路径'][:40]}")
        print("  对照结论：开启扩展后最高相似度应上升；若持平，说明该问题不是措辞问题，需另找原因。")
    except Exception as e:  # noqa: BLE001
        print(f"  ❌ {e}")

    # ---------- 增强③ 阈值 ----------
    段("增强③ 阈值判定：库里没有内容时应明确说「不知道」")
    用例("今天西安的天气怎么样",
         "库里绝对没有的问题",
         "判定应为「库中没有相关内容」，而不是硬给一个答案",
         )
    用例("提交代码之前需要出什么报告",
         "库里有明确答案的问题",
         "判定应为「可信命中」，且第 1 名是【禁令】P-05 提交门禁",
         )

    # ---------- 增强④ 出处 ----------
    段("增强④ 出处完整性：每条结果都要能追回原文")
    try:
        r = R.检索("恢复点是什么", 取前=3)
        ok = True
        for i, h in enumerate(r["结果"], 1):
            有文件 = bool(h.get("来源文件"))
            有标题 = bool(h.get("标题路径"))
            有行号 = h.get("起始行", 0) > 0 and h.get("结束行", 0) > 0
            有指纹 = bool(h.get("内容指纹"))
            print(f"  {i}. 文件{'✅' if 有文件 else '❌'} 标题{'✅' if 有标题 else '❌'} "
                  f"行号{'✅' if 有行号 else '❌'} 内容指纹{'✅' if 有指纹 else '❌'}  "
                  f"→ {h['来源文件']} 行 {h['起始行']}–{h['结束行']}")
            ok = ok and 有文件 and 有标题 and 有行号 and 有指纹
        print(f"\n  出处完整性：{'✅ 四项齐全' if ok else '❌ 有缺项'}")
    except Exception as e:  # noqa: BLE001
        print(f"  ❌ {e}")
        ok = False

    # ---------- 诊断：同一问题在各分组下的最高相似度 ----------
    # 用途：把「默认分组该不该含维护层」从"举例说明"变成"可验证的数据"。
    # 读法：对某个问题，若「维护」组的最高分明显高于「规则」组，说明答案在维护组，
    #       默认只查规则就会漏掉它。
    段("诊断：同一问题在各分组下的最高相似度（判断默认分组是否漏掉了答案）")
    诊断问题 = [
        "提交代码之前需要出什么报告",
        "候选区和正式区的区别是什么",
        "改动前要做什么准备",
        "改文件之前要先做什么",
        "怎么写测试报告",
    ]
    print(f"{'问题':<28}{'规则':>9}{'技能':>9}{'维护':>9}{'全库':>9}   结论")
    print("-" * 90)
    for q in 诊断问题:
        分 = {}
        for g in ("规则", "技能", "维护", "全库"):
            try:
                r = R.检索(q, 取前=1, 分组=g)
                分[g] = r["最高相似度"]
            except Exception:  # noqa: BLE001
                分[g] = float("nan")
        con = ""
        if 分["维护"] > 分["规则"] + 0.005:
            con = "★ 答案在【维护】组 → 默认只查规则会漏"
        elif 分["技能"] > 分["规则"] + 0.005:
            con = "答案偏技能组"
        else:
            con = "答案在规则组，默认可用"
        print(f"{q:<28}{分['规则']:>9.4f}{分['技能']:>9.4f}{分['维护']:>9.4f}{分['全库']:>9.4f}   {con}")

    段("M3 试跑完成")
    print("说明：以上每项都在验证一个**具体实测发现**对应的修复，不是泛泛的『跑通』。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
